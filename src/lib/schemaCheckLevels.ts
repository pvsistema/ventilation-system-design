// Важность проверок схемы — ЕДИНАЯ для панели «Проверка», проверки сразу
// после импорта и сообщений перед расчётом. Раньше каждая из них решала
// сама, что критично, и одна и та же ошибка была то ошибкой, то замечанием.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Критические проверки — из-за них расчёт воздухораспределения невозможен
 * или его результат заведомо неверен (ошибка самой модели сети).
 *
 * НЕ критические (перенесены в замечания):
 *   • неправдоподобное сечение — в файлах АэроСети у камер 300…900 м², у
 *     вентскважин 0,2 м²; так задумано моделью, расчёт с ними совпадает с
 *     АэроСетью. Критично только НЕ заданное сечение («noArea»);
 *   • перемычка с R = 0 — так она записана в исходном файле, расчёт верен;
 *   • расхождение с замерами — вопрос калибровки модели, а не её ошибка.
 */
export const CRITICAL_CHECKS: ReadonlySet<string> = new Set([
  // Расчёт не прошёл
  "solveBlock",
  // Топология: сеть в расчёте не совпадает с чертежом
  "noFan", "components", "deadFan", "tJunction", "selfLoop",
  "brokenBranch", "isolatedBranch", "dupes", "surfaceMulti",
  // Параметры, искажающие сопротивления и тягу
  "invalidValues", "fanNoCurve", "zeroLen", "zeroR", "noArea",
  "shortManualLen", "lostZ",
  // Результат вентилятора недостоверен
  "fanAgainst",
]);

export const isCriticalCheck = (id: string) => CRITICAL_CHECKS.has(id);

/** Сколько строк показывать в одном списке панели (счётчики — полные). */
export const CHECK_LIST_SHOW = 500;
