// ─────────────────────────────────────────────────────────────────────────────
// gasZone.ts — расчёт ПРОТЯЖЁННОСТИ ЗОНЫ ЗАГАЗИРОВАНИЯ по Руководству по
// безопасности, утв. приказом Ростехнадзора от 08.11.2024 № 343
// (раздел II, пункты 7–13, формулы 1–5).
//
// ЗАЧЕМ. Длина загазованного участка — главный вход расчёта взрыва: от неё
// зависит и объём взрывчатой смеси, и начальное давление очага. До сих пор она
// вводилась руками (по умолчанию 100 м), то есть самый влиятельный параметр
// брался «на глаз». Методика даёт его расчётом — от фактического
// метановыделения и времени нарушения проветривания.
//
// ФИЗИКА ОДНОЙ ФРАЗОЙ. Метан поступает с постоянным дебитом I [м³/мин] в течение
// времени t_з [мин]. Чтобы довести смесь до взрывоопасной концентрации c_в [%],
// этого метана хватает на объём V = t_з·I / (0,01·c_в). Разделив объём на
// сечение выработки, получаем длину загазованного участка. Отсюда и вид всех
// трёх формул — различаются они только тем, какое сечение подставляется.
//
//   очистной забой (1):   L_о.з = t_з·I_о.з / (0,01·c_в·(S_о.з + S_з.п))
//   закрепное простр. (2): S_з.п = m·l_н.к
//   непогашенная (3):     L_н.в = t_з·I_н.в / (0,01·c_в·S_н.в)
//   объём непогаш. (4):   V_н.в = Σ L_н.в·S_н.в  по всем N выработкам
//   подготовительная (5): L_п.в = t_з·I_п.в / (0,01·c_в·S_п.в)
//
// ОГРАНИЧЕНИЕ ДЛИНОЙ (п. 13). Если расчёт даёт зону длиннее самой выработки,
// принимается длина выработки. Газу физически некуда деться за её пределы —
// без этого расчёт взрыва получил бы очаг, которого не существует.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Взрывоопасная концентрация метана, при которой ведётся расчёт, % (п. 6).
 *
 * Стехиометрия 9,5 % — не «середина диапазона 5…15 %», а концентрация полного
 * сгорания: именно при ней взрыв даёт наибольшую энергию. Методика предписывает
 * считать по ней, то есть по наихудшему случаю.
 */
export const EXPLOSIVE_CH4_CONC = 9.5;

/**
 * Время загазирования при разработке ПЛА, мин (п. 11).
 *
 * Плановый расчёт — час нарушения проветривания.
 */
export const GAS_TIME_PLA = 60;

/**
 * Минимальное время загазирования при ликвидации аварии, мин (п. 12).
 *
 * Берётся по фактическим данным, но НЕ МЕНЕЕ 150 мин: к моменту, когда до
 * участка добираются, проветривание нарушено уже давно, и часовая оценка
 * занизила бы зону в разы.
 */
export const GAS_TIME_EMERGENCY_MIN = 150;

/**
 * Метановыделение в непогашенную выработку по умолчанию, м³/мин (сноска к ф. 3).
 *
 * Методика прямо разрешает принимать 0,5 при отсутствии фактических данных —
 * замерить дебит в частично сохраняемой выработке обычно нечем.
 */
export const DEFAULT_I_NEPOGASH = 0.5;

/** Где формируется зона загазирования. */
export type GasZoneKind =
  /** Очистной забой с полным обрушением кровли — формула (1). */
  | "longwall"
  /** Частично сохраняемая либо непогашенная выработка — формула (3). */
  | "preserved"
  /** Тупиковая подготовительная выработка — формула (5). */
  | "heading";

/** Подпись вида зоны для протокола. */
export function gasZoneKindLabel(k: GasZoneKind): string {
  return k === "longwall" ? "Очистной забой (ф. 1)"
    : k === "preserved" ? "Непогашенная выработка (ф. 3)"
    : "Подготовительная выработка (ф. 5)";
}

/** Исходные данные расчёта. */
export interface GasZoneInput {
  kind: GasZoneKind;
  /** Время загазирования t_з, мин (п. 11–12). */
  time_min: number;
  /** Фактическое метановыделение I, м³/мин. */
  emission_m3min: number;
  /** Площадь сечения выработки в свету S, м². */
  area_m2: number;
  /**
   * Вынимаемая мощность пласта m, м — только для очистного забоя (ф. 2).
   * Вместе с шагом обрушения даёт сечение закрепного пространства.
   */
  seamThickness_m?: number;
  /** Шаг обрушения непосредственной кровли l_н.к, м — только для забоя (ф. 2). */
  caveStep_m?: number;
  /**
   * Фактическая длина выработки, м (п. 13). Если задана и расчёт её превысил,
   * зона обрезается по ней.
   */
  branchLength_m?: number;
  /** Взрывоопасная концентрация c_в, % (по умолчанию 9,5 — п. 6). */
  conc_pct?: number;
}

/** Результат расчёта. */
export interface GasZoneResult {
  /** Протяжённость зоны по формуле, до ограничения длиной выработки, м. */
  lengthRaw_m: number;
  /** Протяжённость к применению, м. */
  length_m: number;
  /** Объём загазированной зоны, м³ — длина × суммарное сечение. */
  volume_m3: number;
  /** Суммарное сечение, вошедшее в расчёт, м² (у забоя — с закрепным). */
  areaTotal_m2: number;
  /** Сечение закрепного пространства S_з.п, м² (ф. 2); 0 — если не применимо. */
  areaCaved_m2: number;
  /** Номер применённой формулы. */
  formula: 1 | 3 | 5;
  /** Обрезана ли зона фактической длиной выработки (п. 13). */
  clampedByLength: boolean;
  /** Пояснение для протокола. */
  note: string;
}

/**
 * Протяжённость зоны загазирования по формулам 1, 3 или 5.
 *
 * Возвращает null, когда считать нечего: нулевое метановыделение, нулевое время
 * или нулевое сечение. Подставлять вместо них что-то своё нельзя — результат
 * выглядел бы полноценным расчётом, не будучи им.
 */
export function calcGasZone(input: GasZoneInput): GasZoneResult | null {
  const conc = input.conc_pct ?? EXPLOSIVE_CH4_CONC;
  const { time_min: t, emission_m3min: I, area_m2: S } = input;

  if (!(t > 0) || !(I > 0) || !(S > 0) || !(conc > 0)) return null;

  // Сечение закрепного пространства — только для очистного забоя (ф. 2).
  // Методика требует считать зону по СУММАРНОМУ сечению: метан заполняет и
  // забой, и закрепное пространство за крепью, и делить их нельзя.
  const areaCaved = input.kind === "longwall"
    ? Math.max(0, (input.seamThickness_m ?? 0) * (input.caveStep_m ?? 0))
    : 0;

  const areaTotal = S + areaCaved;
  if (!(areaTotal > 0)) return null;

  const formula: 1 | 3 | 5 = input.kind === "longwall" ? 1
    : input.kind === "preserved" ? 3 : 5;

  // Общий вид всех трёх формул: L = t·I / (0,01·c_в·S)
  const raw = (t * I) / (0.01 * conc * areaTotal);
  if (!Number.isFinite(raw) || raw <= 0) return null;

  // п. 13: зона не может быть длиннее самой выработки.
  const limit = input.branchLength_m && input.branchLength_m > 0 ? input.branchLength_m : 0;
  const clamped = limit > 0 && raw > limit;
  const length = clamped ? limit : raw;

  return {
    lengthRaw_m: round1(raw),
    length_m: round1(length),
    volume_m3: Math.round(length * areaTotal),
    areaTotal_m2: round2(areaTotal),
    areaCaved_m2: round2(areaCaved),
    formula,
    clampedByLength: clamped,
    note: clamped
      ? `Расчёт дал ${round1(raw)} м — принята длина выработки ${round1(limit)} м (п. 13)`
      : `Протяжённость по формуле (${formula})`,
  };
}

/**
 * Суммарный объём зоны загазирования нескольких непогашенных выработок (ф. 4).
 *
 * V_н.в = Σ L_н.в·S_н.в по всем N выработкам, примыкающим к очистному забою.
 * Отдельная формула нужна потому, что выработки разные: у каждой своё сечение и
 * своё метановыделение, и просто умножить одну длину на одно сечение нельзя.
 */
export function totalPreservedVolume(zones: Array<{ length_m: number; area_m2: number }>): number {
  let v = 0;
  for (const z of zones) {
    if (z.length_m > 0 && z.area_m2 > 0) v += z.length_m * z.area_m2;
  }
  return Math.round(v);
}

/**
 * Время загазирования по условиям расчёта (п. 11–12).
 *
 * duringEmergency — расчёт в ходе ликвидации аварии: берётся фактическое время,
 * но не менее 150 мин. Иначе плановые 60 мин для ПЛА.
 */
export function gasZoneTime(duringEmergency: boolean, factual_min?: number): number {
  if (!duringEmergency) return GAS_TIME_PLA;
  const f = factual_min && factual_min > 0 ? factual_min : 0;
  return Math.max(GAS_TIME_EMERGENCY_MIN, f);
}

function round1(v: number): number { return Math.round(v * 10) / 10; }
function round2(v: number): number { return Math.round(v * 100) / 100; }
