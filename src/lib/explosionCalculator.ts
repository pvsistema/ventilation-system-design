/**
 * Тротиловый эквивалент облака (Методика №415, прил. по ТВС):
 *   m_пр = (q_г / q_ТНТ) · m · Z
 * где Z — коэффициент участия горючего во взрывном превращении
 * (0.1 — дефлаграция в открытом пространстве, 0.5 — замкнутый объём).
 *
 * Газ и пыль считаются по-разному — у них разная единица концентрации:
 *   газ  (vol%): объём горючего = V·c/100,  энергия = объём · qCombust [МДж/м³]
 *   пыль (g/m3): масса пыли     = V·c/1000, энергия = масса · qCombust [МДж/кг]
 */
function gasToTnt(gas: GasType, volume_m3: number, concentration: number, z: number): number {
  // Химическая энергия облака, МДж
  const E_chem = gas.unit === "g/m3"
    ? (volume_m3 * concentration / 1000) * gas.qCombust  // кг пыли × МДж/кг
    : (volume_m3 * concentration / 100)  * gas.qCombust; // м³ газа × МДж/м³
  // Энергия, участвующая во взрывном превращении (коэффициент Z по №415)
  const E_mech = E_chem * z * 1000; // → кДж
  // Тротиловый эквивалент
  return E_mech / Q_TNT;
}

/** Тротиловый эквивалент из массы ВВ */
function massToTnt(expl: ExplosiveType, mass_kg: number): number {
  return mass_kg * tntEquivalent(expl);
}

/** Перевод кгс/см² → кПа (коэффициенты Садовского даны в кгс/см²) */
const KGF_CM2_TO_KPA = 98.07;

/**
 * Нижняя граница применимости формулы Садовского — приведённое расстояние
 * r̄ = r / Q^(1/3) = 1, то есть r = Q^(1/3) метров. Ближе к заряду формула
 * расходится: члены 1/r̄² и 1/r̄³ растут неограниченно и дают величины,
 * не имеющие физического смысла (для 97 кг при r = 1 м получалось
 * 74 000 кПа и скорость фронта 8 500 м/с — быстрее детонации любого ВВ).
 */
const R_BAR_MIN = 1.0;

/** Наименьшее расстояние, на котором формула ещё применима, м */
export function minValidRadius(q_tnt: number): number {
  if (q_tnt <= 0) return 0;
  return Math.round(R_BAR_MIN * Math.pow(q_tnt, 1 / 3) * 100) / 100;
}

/**
 * Давление во фронте ударной волны по формуле Садовского (Методика ГД):
 * ΔP = 0.84/r̄ + 2.7/r̄² + 7.15/r̄³  [кгс/см²]
 * где r̄ = r / Q_tnt^(1/3) — приведённое расстояние.
 * ВАЖНО: исходные коэффициенты дают результат в кгс/см², поэтому
 * результат переводится в кПа умножением на 98.07.
 * Источник: Садовский М.А. «Механическое действие взрыва».
 * Согласуется с Методикой №415 (ТВС) при Z = 0.1.
 */
function sadovskyDeltaPRaw(r_m: number, q_tnt: number): number {
  if (q_tnt <= 0 || r_m <= 0) return 0;
  // ГРАНИЦА ПРИМЕНИМОСТИ соблюдается здесь, а не только при выводе ΔP_max.
  // Ближе r̄ = 1 формула расходится: на 1 м от заряда 95 кг она давала
  // 72 500 кПа, на 0.5 м — 555 700 кПа. Прежняя отсечка `rBar < 0.1 → 10000`
  // не спасала, а вносила разрыв: при r̄ = 0.1001 выходило 726 350 кПа,
  // при r̄ = 0.0999 — сразу 10 000, то есть ближе к заряду давление
  // оказывалось МЕНЬШЕ, чем дальше от него.
  // Внутри этой зоны методика параметры волны не определяет, поэтому
  // давление принимается равным значению на самой границе (плато).
  const rBar = Math.max(r_m / Math.pow(q_tnt, 1 / 3), R_BAR_MIN);
  const dP_kgf = 0.84 / rBar + 2.7 / (rBar * rBar) + 7.15 / (rBar * rBar * rBar);
  return dP_kgf * KGF_CM2_TO_KPA;
}

/** То же, округлённое до 0,1 кПа — для вывода пользователю */
function sadovskyDeltaP(r_m: number, q_tnt: number): number {
  return Math.round(sadovskyDeltaPRaw(r_m, q_tnt) * 10) / 10;
}

/**
 * Импульс положительной фазы, Па·с — по Методике №415 (прил. по ТВС):
 *   i = 123 · m_пр^0.66 / r
 *
 * Коэффициент 123 взят из той же методики, что и формула давления, — иначе
 * импульс и давление считались бы по разным источникам. Прежний коэффициент
 * 200 (из другой редакции формулы Садовского, в иных единицах) завышал
 * импульс ровно на 68 % на всех расстояниях.
 */
function sadovskyImpulse(r_m: number, q_tnt: number): number {
  if (q_tnt <= 0 || r_m <= 0) return 0;
  // Та же граница применимости, что и у давления: 123·m^0.66/r при r → 0
  // растёт неограниченно. Внутри границы берём значение на ней (плато).
  const r = Math.max(r_m, minValidRadius(q_tnt));
  const i_Pa_s = 123 * Math.pow(q_tnt, 0.66) / r;
  return Math.round(i_Pa_s * 10) / 10;
}

/**
 * Длительность фазы сжатия для КОМПАКТНОГО ЗАРЯДА (ВВ), с.
 *
 * Выводится из определения импульса: i = ΔP · τ, откуда τ = i / ΔP.
 * Обе величины берутся из Методики №415, поэтому длительность
 * согласована с ними и не вводит нового источника данных.
 *
 * Нужна, чтобы импульсы газовой и тротиловой веток были СОПОСТАВИМЫ:
 * они отличаются на порядки не из-за разных формул, а из-за разной
 * длительности нагружения — у ВВ это единицы миллисекунд, у газовой
 * дефлаграции в выработке десятки.
 */
export function tntPhaseDuration(r_m: number, q_tnt: number): number {
  const dp = sadovskyDeltaPRaw(r_m, q_tnt); // кПа
  if (dp <= 0) return 0;
  return sadovskyImpulse(r_m, q_tnt) / (dp * 1000); // с
}

/** Скорость фронта ударной волны (м/с) через давление: D = C0 * √(1 + 6/7 * ΔP/P0) */
function waveFrontSpeed(deltaP_kPa: number): number {
  return Math.round(C0 * Math.sqrt(1 + (6 / 7) * (deltaP_kPa / P0)) * 10) / 10;
}

/**
 * Опорные точки коэффициента отражения от стенок выработки.
 * Чем уже выработка, тем сильнее волна канализируется и тем выше давление.
 * Значения эмпирические, согласованы с прежними ступенями.
 */
const WALL_FACTOR_POINTS: Array<{ area: number; k: number }> = [
  { area:  5, k: 2.0 },
  { area: 15, k: 1.8 },
  { area: 30, k: 1.5 },
  { area: 50, k: 1.3 },
];

/**
 * Коэффициент отражения от стенок горной выработки — ПЛАВНЫЙ.
 *
 * Раньше коэффициент был ступенчатым (<10 → 2.0, <20 → 1.8, <40 → 1.5,
 * иначе 1.3). Из-за этого две почти одинаковые выработки попадали в разные
 * ступени: 19.9 м² давало 1.8, а 20.0 м² — уже 1.5, то есть изменение
 * сечения на 0.1 м² роняло расчётное давление на 17 % и заметно двигало
 * границы зон поражения. Теперь между опорными точками идёт линейная
 * интерполяция, за их пределами — плато.
 */
export function wallReflectionFactor(area_m2: number): number {
  const pts = WALL_FACTOR_POINTS;
  if (area_m2 <= 0) return 1.5;               // сечение не задано
  if (area_m2 <= pts[0].area) return pts[0].k; // очень узкие — плато 2.0
  const last = pts[pts.length - 1];
  if (area_m2 >= last.area) return last.k;     // широкие — плато 1.3
  for (let i = 0; i < pts.length - 1; i++) {
    const a = pts[i], b = pts[i + 1];
    if (area_m2 <= b.area) {
      const t = (area_m2 - a.area) / (b.area - a.area);
      return Math.round((a.k + (b.k - a.k) * t) * 1000) / 1000;
    }
  }
  return last.k;
}

// ─── КАНАЛЬНАЯ МОДЕЛЬ РАСПРОСТРАНЕНИЯ ────────────────────────────────────────
/**
 * ПОЧЕМУ ОНА НУЖНА.
 *
 * Формула Садовского описывает СФЕРИЧЕСКИЙ разлёт в открытом воздухе: энергия
 * размазывается по поверхности шара, давление падает почти как 1/r³. В горной
 * выработке волна уже через несколько метров упирается в стенки и дальше идёт
 * по КАНАЛУ постоянного сечения: энергия в объём не рассеивается, давление
 * падает только на трении о стенки, местных сопротивлениях и делении потока
 * на сопряжениях.
 *
 * Разница не в процентах, а в порядках. Для 95 кг ТНТ в выработке 12 м²
 * сферическая модель давала границу 6 кПа на 127 м, тогда как «Аэросеть»
 * на той же сети красит ветви на километры. Прежний коэффициент
 * wallReflectionFactor этого не лечил: он умножал давление на постоянное
 * число (1.3…2.0) и не менял сам ЗАКОН затухания — на 10 м это почти
 * незаметно, а на 500 м кривая всё равно уже в нуле.
 *
 * КАК СЧИТАЕМ.
 *   1) Ближняя зона (r ≤ r_tr) — сферическая, по Садовскому. Пока фронт не
 *      заполнил сечение, волна действительно расходится шаром.
 *   2) Переход r_tr ≈ k_tr·√S — момент, когда фронт упёрся в стенки.
 *   3) Дальняя зона — канальная: ΔP(L) = ΔP(r_tr)·exp(−β·(L−r_tr)),
 *      где β = λ/(2·d_г) — погонный декремент затухания, d_г = 4S/P.
 *
 * Экспонента — это решение уравнения затухания плоской волны в трубе с
 * трением: dΔP/dx = −(λ/2d)·ΔP. Именно такой закон даёт характерную для
 * шахт дальнобойность в сотни метров и километры вместо десятков метров.
 */

/** Коэффициент перехода сфера → канал: r_tr = K_TRANSITION · √S */
const K_TRANSITION = 2.0;

/**
 * Коэффициент сопротивления λ для ЗАТУХАНИЯ УДАРНОЙ ВОЛНЫ (безразмерный).
 *
 * ВАЖНО: это НЕ коэффициент стационарного трения из аэродинамики выработки.
 * Ударная волна проходит выработку за доли секунды, пограничный слой
 * развиться не успевает, и фактические потери на порядок ниже, чем при
 * установившемся потоке. Прежнее значение 0.05 (взятое как для стационарного
 * течения в арочной крепи) гасило волну втрое быстрее реального и давало
 * зону 10 кПа на 737 м там, где «Аэросеть» показывает километры.
 *
 *   0.005…0.01 — гладкие бетонные стволы, набрызг-бетон;
 *   0.015…0.025 — типовые выработки с арочной крепью (по умолчанию 0.02);
 *   0.03…0.05  — сильно загромождённые, с затяжкой и оборудованием.
 */
export const LAMBDA_DEFAULT = 0.02;

/**
 * Начальное избыточное давление продуктов взрыва газовоздушной смеси
 * в замкнутом объёме, кПа.
 *
 * При дефлаграции метановоздушной смеси в выработке давление в очаге
 * поднимается примерно в 8…9 раз от атмосферного, то есть избыточное
 * составляет ~0.7…0.9 МПа. В «Аэросети» этот параметр задаётся явно
 * (на скриншоте P = 282 кПа) — у нас он тоже вынесен в настройку,
 * а 282 кПа принято значением по умолчанию для сверки.
 */
export const GAS_P0_DEFAULT = 282;

/**
 * Начальное давление продуктов взрыва, кПа — зависит от ДЛИНЫ участка
 * И от ЭНЕРГИИ смеси.
 *
 * ФИЗИКА. Давление в замкнутом объёме при сгорании определяется удельным
 * энерговыделением: P_изб ∝ E_v (энергия на кубометр смеси). Длина участка
 * добавляет разгон фронта пламени — чем дольше пламя ускоряется на
 * турбулентности от стенок, тем выше давление, но с насыщением.
 *
 *     ΔP₀ = K · L^n · (E_v / E_v_ref)
 *
 * ПОЧЕМУ ТАК, А НЕ ТОЛЬКО ПО ДЛИНЕ. Раньше формула была ΔP₀ = K·L^n без
 * энергии, и это разрывало расчётную цепочку: вид газа, его концентрация
 * и коэффициент участия Z считались, выводились на экран — но на зоны
 * поражения не влияли вообще. Смесь у нижнего предела 5.5 % давала те же
 * зоны, что стехиометрическая 9.5 %, а водород — те же, что ацетилен.
 *
 * КАЛИБРОВКА. Множитель (E_v/E_v_ref) равен единице для эталона —
 * метановоздушной смеси стехиометрической концентрации при Z = 0.5.
 * Поэтому контрольные точки «Аэросети» сохраняются в точности:
 *   L = 50 м  → 209 кПа
 *   L = 100 м → 282 кПа
 *
 * Ограничения: снизу 20 кПа (короткий участок не разгоняет пламя), сверху
 * 900 кПа — предел давления продуктов сгорания углеводородовоздушной смеси
 * в замкнутом объёме (около 9 атмосфер).
 */
export const GAS_P0_COEF = 38.5358;
export const GAS_P0_EXP  = 0.43219;

/**
 * Эталонная удельная энергия: метан, стехиометрия 9.5 %, Z = 0.5.
 * E_v = 33.8 МДж/м³ · 0.095 · 0.5 = 1.6055 МДж на м³ смеси.
 */
export const GAS_EV_REF = 1.6055;

/**
 * Удельная энергия смеси, МДж на кубометр СМЕСИ.
 *
 * Учитывает три ограничения:
 *   1) горючего больше стехиометрии — сгорает только стехиометрическая
 *      доля, остального кислорода не хватает;
 *   2) непрореагировавший избыток работает БАЛЛАСТОМ: поглощает тепло,
 *      снижает температуру продуктов и давление. Отсюда множитель
 *      stoich/conc для богатых смесей — раньше его не было, и смеси
 *      12 % и 14.9 % давали ровно то же, что стехиометрические 9.5 %;
 *   3) коэффициент участия Z по Методике №415.
 */
export function gasEnergyDensity(gas: GasType, concentration: number, z: number): number {
  if (concentration <= 0 || z <= 0) return 0;
  // Доля горючего, которая реально сгорает (ограничена кислородом)
  const burned = Math.min(concentration, gas.stoichConc);
  // Энергия на м³ смеси: у газа концентрация объёмная (%), у пыли — г/м³
  const e = gas.unit === "g/m3"
    ? (burned / 1000) * gas.qCombust   // кг пыли в м³ × МДж/кг
    : (burned / 100)  * gas.qCombust;  // м³ газа в м³ смеси × МДж/м³
  // Балласт: избыток горючего сверх стехиометрии охлаждает продукты
  const ballast = concentration > gas.stoichConc ? gas.stoichConc / concentration : 1;
  return e * ballast * z;
}

/**
 * ΔP₀ в очаге по длине участка и удельной энергии смеси, кПа.
 * energyDensity не задана — берётся эталонная (метан, стехиометрия, Z=0.5),
 * то есть формула вырождается в прежнюю зависимость только от длины.
 */
export function gasInitialPressure(zoneLength_m: number, energyDensity_MJ_m3?: number): number {
  if (!Number.isFinite(zoneLength_m) || zoneLength_m <= 0) return 0;
  const ev = energyDensity_MJ_m3 && energyDensity_MJ_m3 > 0 ? energyDensity_MJ_m3 : GAS_EV_REF;
  const p = GAS_P0_COEF * Math.pow(zoneLength_m, GAS_P0_EXP) * (ev / GAS_EV_REF);
  return Math.round(Math.min(900, Math.max(20, p)) * 10) / 10;
}

/** Гидравлический диаметр выработки d_г = 4S/P, м */
export function hydraulicDiameter(area_m2: number, perimeter_m?: number): number {
  if (area_m2 <= 0) return 0;
  // Периметр не задан — принимаем круглое сечение: P = 2√(πS), d = 2√(S/π)
  const P = perimeter_m && perimeter_m > 0 ? perimeter_m : 2 * Math.sqrt(Math.PI * area_m2);
  return (4 * area_m2) / P;
}

/** Параметры канала для затухания волны вдоль одной выработки */
export interface ChannelParams {
  /** Сечение выработки, м² */
  area_m2: number;
  /** Периметр, м (не задан — считается как для круга) */
  perimeter_m?: number;
  /** Коэффициент сопротивления λ (не задан — LAMBDA_DEFAULT) */
  lambda?: number;
}

/**
 * Погонный декремент затухания β, 1/м: ΔP(x) = ΔP₀·exp(−β·x).
 *
 * β = λ / (2·d_г). Чем уже выработка, тем быстрее гаснет волна — это
 * ПРОТИВОПОЛОЖНО прежней логике wallReflectionFactor, где узкая выработка
 * просто усиливала давление постоянным множителем. Физически верно именно
 * так: в узком канале выше отношение периметра к площади, значит больше
 * потери на трении о стенки на каждом метре пути.
 */
export function channelDecay(ch: ChannelParams): number {
  const d = hydraulicDiameter(ch.area_m2, ch.perimeter_m);
  if (d <= 0) return 0;
  const lambda = ch.lambda && ch.lambda > 0 ? ch.lambda : LAMBDA_DEFAULT;
  return lambda / (2 * d);
}

/** Расстояние перехода от сферического разлёта к канальному, м */
export function transitionRadius(area_m2: number): number {
  if (area_m2 <= 0) return 0;
  return K_TRANSITION * Math.sqrt(area_m2);
}

/**
 * Коэффициент прохождения ДАВЛЕНИЯ через сопряжение выработок.
 *
 * ПОЧЕМУ НЕ ПРОСТОЕ ДЕЛЕНИЕ ПО СЕЧЕНИЯМ. Раньше здесь стояло
 * split = S_i / ΣS_исх, то есть давление делилось между исходящими ветвями
 * пропорционально их площади. Это неверно: ΔP — величина интенсивная, она
 * не делится. Делится поток энергии, а фронт волны проходит в каждую ветвь
 * почти целиком, теряя лишь часть на отражении от расширения канала.
 *
 * Прежняя модель давала на обычном тройнике множитель 0.5, и после шести
 * таких узлов от волны оставалось 1.6 % — окраска обрывалась в середине
 * схемы, хотя «Аэросеть» на той же сети красит выработки до края.
 *
 * АКУСТИЧЕСКАЯ МОДЕЛЬ. Волна, идущая по каналу сечением S_вх, встречает
 * разрыв площади: суммарное сечение исходящих ветвей ΣS_исх. Коэффициент
 * прохождения ПО ДАВЛЕНИЮ — стандартное решение задачи о падении волны
 * на скачок импеданса (для канала Z ~ 1/S):
 *
 *     τ = 2·S_вх / (S_вх + ΣS_исх)
 *
 * Это ЕДИНСТВЕННЫЙ множитель: он уже описывает, что часть волны отражается
 * обратно. Дополнительно делить прошедшее давление по ветвям НЕЛЬЗЯ —
 * давление интенсивная величина, в каждую ветвь входит один и тот же
 * фронт τ·ΔP. Делится поток энергии, но он пропорционален S·ΔP², и баланс
 * сходится сам: суммарная энергия за узлом не превышает вошедшую.
 *
 * Для типового тройника (S_вх = S₁ = S₂) получается τ = 2/3 ≈ 0.67 в каждую
 * ветвь вместо прежних 0.5. После шести узлов остаётся 8.8 % против 1.6 %.
 *
 * @param areaIn   сечение выработки, ПО КОТОРОЙ волна пришла, м²
 * @param areaOutTotal суммарное сечение ВСЕХ исходящих ветвей, м²
 */
export function junctionTransmission(areaIn: number, areaOutTotal: number): number {
  if (areaIn <= 0 || areaOutTotal <= 0) return 1;
  return Math.min(1, (2 * areaIn) / (areaIn + areaOutTotal));
}

/**
 * Давление во фронте на расстоянии L по ВЫРАБОТКЕ, кПа.
 *
 * Ближняя зона — Садовский (сфера), дальняя — экспоненциальное затухание
 * в канале. В точке сшивки r_tr обе ветви дают одно значение, поэтому
 * функция непрерывна и монотонно убывает.
 *
 * @param pathLoss_dB — накопленные потери на ПРЕДЫДУЩИХ участках пути
 *        (деление потока на сопряжениях, местные сопротивления), в виде
 *        безразмерного множителя ≤ 1. Для одиночной выработки равен 1.
 */
export function channelPressureAt(
  L_m: number,
  q_tnt: number,
  ch: ChannelParams,
  pathFactor = 1,
): number {
  if (q_tnt <= 0) return 0;
  const rMin = R_BAR_MIN * Math.pow(q_tnt, 1 / 3);
  const rTr  = Math.max(transitionRadius(ch.area_m2), rMin);
  const L    = Math.max(L_m, rMin);

  // Ближняя зона — чистая сфера по Садовскому
  if (L <= rTr) {
    return Math.round(sadovskyDeltaPRaw(L, q_tnt) * pathFactor * 10) / 10;
  }
  // Дальняя зона — канал: сшивка в r_tr и экспоненциальное затухание
  const dpTr = sadovskyDeltaPRaw(rTr, q_tnt);
  const beta = channelDecay(ch);
  const dp   = dpTr * Math.exp(-beta * (L - rTr));
  return Math.round(dp * pathFactor * 10) / 10;
}

/**
 * Импульс на расстоянии L по выработке, Па·с.
 * В канале импульс затухает медленнее давления (фаза сжатия растягивается),
 * поэтому берётся половинный декремент.
 */
export function channelImpulseAt(
  L_m: number,
  q_tnt: number,
  ch: ChannelParams,
  pathFactor = 1,
): number {
  if (q_tnt <= 0) return 0;
  const rMin = R_BAR_MIN * Math.pow(q_tnt, 1 / 3);
  const rTr  = Math.max(transitionRadius(ch.area_m2), rMin);
  const L    = Math.max(L_m, rMin);
  const base = 123 * Math.pow(q_tnt, 0.66);
  if (L <= rTr) {
    return Math.round((base / L) * pathFactor * 10) / 10;
  }
  const iTr  = base / rTr;
  const beta = channelDecay(ch) * 0.5;
  return Math.round(iTr * Math.exp(-beta * (L - rTr)) * pathFactor * 10) / 10;
}

// ─── ГАЗОВАЯ МОДЕЛЬ: ПЛОСКАЯ ВОЛНА ОТ ЗАГАЗОВАННОГО УЧАСТКА ─────────────────
/**
 * ПОЧЕМУ ДЛЯ ГАЗА ОТДЕЛЬНАЯ МОДЕЛЬ.
 *
 * Для ВВ источник — компактный заряд: волна сначала расходится шаром, и
 * формула Садовского здесь уместна. Для газа источник принципиально другой —
 * это ПРОТЯЖЁННЫЙ загазованный участок выработки длиной в десятки метров.
 * Он занимает всё сечение, поэтому волна с самого начала плоская: никакого
 * сферического разлёта нет, и «делить энергию на поверхность шара» неверно.
 *
 * Прежний расчёт применял к газу ту же сферическую ближнюю зону, и уже на
 * r_tr = 2√S ≈ 7 м от 35 кг ТНТ оставалось 174 кПа вместо стартовых 1046 —
 * то есть 85 % энергии «терялось» в первых семи метрах ещё до входа в канал.
 * Отсюда и расхождение с «Аэросетью» в разы по дальности зон.
 *
 * КАК СЧИТАЕМ ТЕПЕРЬ (как в «Аэросети»):
 *   • внутри загазованного участка (L ≤ L_газ/2 от центра) давление
 *     постоянно и равно начальному ΔP₀ — весь объём реагирует;
 *   • за границей участка — экспоненциальное затухание плоской волны
 *     в канале: ΔP(L) = ΔP₀ · exp(−β·(L − L_газ/2)).
 *
 * Тротиловый эквивалент при этом сохраняется в результате для отчётности,
 * но на форму кривой не влияет — она определяется ΔP₀ и геометрией канала.
 */

/** Параметры источника-газа: протяжённый загазованный участок */
export interface GasSourceParams {
  /** Длина загазованного участка, м */
  zoneLength_m: number;
  /** Начальное избыточное давление в очаге, кПа */
  initialPressure_kPa: number;
}

/** Полуразмер загазованного участка, м — от центра до его границы */
function gasHalfLength(src: GasSourceParams): number {
  return Math.max(src.zoneLength_m, 0) / 2;
}

/**
 * Давление плоской волны на расстоянии L от ЦЕНТРА загазованного участка, кПа.
 * Внутри участка — плато ΔP₀, снаружи — экспоненциальное затухание.
 */
export function gasChannelPressureAt(
  L_m: number,
  src: GasSourceParams,
  ch: ChannelParams,
  pathFactor = 1,
): number {
  const p0 = src.initialPressure_kPa;
  if (p0 <= 0) return 0;
  const half = gasHalfLength(src);
  const L = Math.max(L_m, 0);
  if (L <= half) return Math.round(p0 * pathFactor * 10) / 10;
  const beta = channelDecay(ch);
  return Math.round(p0 * Math.exp(-beta * (L - half)) * pathFactor * 10) / 10;
}

/**
 * Скорость звука в продуктах сгорания, м/с.
 *
 * Продукты горения метановоздушной смеси нагреты до ~2000 K, и скорость
 * звука в них вдвое выше, чем в холодном воздухе: c = √(γRT/M) ≈ 700–900 м/с.
 * С учётом остывания при расширении принято 680 м/с (2·C₀).
 *
 * Это НЕ C₀: раньше в формуле длительности стояла скорость звука в холодном
 * воздухе, что вдвое завышало время разгрузки очага.
 */
export const C_PRODUCTS = 680;

/**
 * Длительность фазы сжатия для газового взрыва, с.
 *
 * Физически это время разгрузки загазованного участка: волна разрежения
 * идёт от границы очага вглубь со скоростью звука в продуктах. Очаг
 * разгружается в ОБЕ стороны, поэтому в расчёт идёт полудлина.
 *
 *     τ = (L/2) / c_прод
 *
 * ПРЕЖНЯЯ ОШИБКА: стояло τ = L / C₀ — полная длина, делённая на скорость
 * звука в ХОЛОДНОМ воздухе. Это давало вчетверо завышенную длительность
 * (для L = 100 м — 294 мс вместо 74 мс) и такой же завышенный импульс.
 */
export function gasPhaseDuration(src: GasSourceParams): number {
  return Math.max(gasHalfLength(src), 0.5) / C_PRODUCTS;
}

/**
 * Импульс плоской волны, Па·с: i = ΔP · τ.
 *
 * ПОЧЕМУ У ГАЗА ИМПУЛЬС НАМНОГО БОЛЬШЕ, ЧЕМ У ВВ. Это не ошибка расчёта,
 * а разные режимы нагружения. Компактный заряд ВВ даёт короткий удар:
 * длительность фазы сжатия — единицы миллисекунд. Газовая дефлаграция в
 * выработке работает как длинный поршень: продукты разгружаются десятки
 * миллисекунд, и при том же давлении импульс на порядок-два выше.
 *
 * Чтобы величины были сопоставимы, длительность фазы возвращается в
 * результате отдельным полем (phaseDuration_ms) для обеих веток — тогда
 * видно, что импульсы отличаются именно из-за τ, а не из-за разнобоя
 * в формулах.
 *
 * В канале импульс затухает медленнее давления, поэтому декремент половинный.
 */
export function gasChannelImpulseAt(
  L_m: number,
  src: GasSourceParams,
  ch: ChannelParams,
  pathFactor = 1,
): number {
  const p0 = src.initialPressure_kPa;
  if (p0 <= 0) return 0;
  const half = gasHalfLength(src);
  const i0 = p0 * 1000 * gasPhaseDuration(src); // Па·с
  const L = Math.max(L_m, 0);
  if (L <= half) return Math.round(i0 * pathFactor * 10) / 10;
  const beta = channelDecay(ch) * 0.5;
  return Math.round(i0 * Math.exp(-beta * (L - half)) * pathFactor * 10) / 10;
}

/** Длина пути от центра очага, на которой ΔP падает до заданного, м */
export function gasChannelDistanceAtPressure(
  targetP_kPa: number,
  src: GasSourceParams,
  ch: ChannelParams,
  pathFactor = 1,
): number {
  const p0 = src.initialPressure_kPa * pathFactor;
  if (targetP_kPa <= 0 || p0 <= 0) return 0;
  const half = gasHalfLength(src);
  // Порог выше начального давления — зона не образуется
  if (targetP_kPa >= p0) return Math.round(half);
  const beta = channelDecay(ch);
  if (beta <= 0) return Math.round(half);
  return Math.round(half + Math.log(p0 / targetP_kPa) / beta);
}

/**
 * Длина пути по выработке, на которой давление падает до заданного, м.
 * Аналог radiusAtPressure, но для канальной модели.
 */
export function channelDistanceAtPressure(
  targetP_kPa: number,
  q_tnt: number,
  ch: ChannelParams,
  pathFactor = 1,
): number {
  if (targetP_kPa <= 0 || q_tnt <= 0) return 0;
  const rMin = R_BAR_MIN * Math.pow(q_tnt, 1 / 3);
  const rTr  = Math.max(transitionRadius(ch.area_m2), rMin);
  const dpTr = sadovskyDeltaPRaw(rTr, q_tnt) * pathFactor;

  // Порог достигается ещё в сферической зоне — ищем там (бинарный поиск)
  if (targetP_kPa >= dpTr) {
    let lo = rMin, hi = rTr;
    if (sadovskyDeltaPRaw(rMin, q_tnt) * pathFactor <= targetP_kPa) return Math.round(rMin);
    for (let i = 0; i < 60; i++) {
      const mid = (lo + hi) / 2;
      if (sadovskyDeltaPRaw(mid, q_tnt) * pathFactor > targetP_kPa) lo = mid; else hi = mid;
    }
    return Math.round((lo + hi) / 2);
  }
  // Дальняя зона — решаем экспоненту аналитически
  const beta = channelDecay(ch);
  if (beta <= 0) return Math.round(rTr);
  const L = rTr + Math.log(dpTr / targetP_kPa) / beta;
  return Math.round(L);
}

// ─── Пороги поражения (кПа) ───────────────────────────────────────────────────
/**
 * Пороги зон поражения по избыточному давлению, кПа.
 *
 * Вынесены в справочник: ряд порогов в разных документах различается.
 * По умолчанию 100 / 50 / 30 / 10 — как было исторически. В большинстве
 * отечественных таблиц поражения человека используется ряд
 * 100 / 60 / 40 / 20, поэтому предприятие может выставить свой.
 */
export interface ExplosionThresholds {
  lethal: number;   // ≥ — летальный исход
  heavy: number;    // ≥ — тяжёлые поражения
  medium: number;   // ≥ — средние поражения
  light: number;    // ≥ — лёгкие поражения
  /**
   * Граница безопасной зоны — НЕ порог классификации, а расстояние,
   * дальше которого воздействие пренебрежимо мало. По нему строится
   * внешний контур зон и предел шкалы волны. 5.99 кПа — как в «Аэросети».
   */
  safeLimit: number;
}

/** Ряд по умолчанию — исторический для этой программы */
export const DEFAULT_EXPLOSION_THRESHOLDS: ExplosionThresholds = {
  lethal: 100, heavy: 50, medium: 30, light: 10, safeLimit: 5.99,
};

/** Типовой ряд отечественных таблиц поражения человека */
export const TYPICAL_EXPLOSION_THRESHOLDS: ExplosionThresholds = {
  lethal: 100, heavy: 60, medium: 40, light: 20, safeLimit: 5.99,
};

/**
 * Приведение порогов к корректному виду: ряд должен строго убывать,
 * иначе бинарный поиск радиуса даст вложенные зоны в неверном порядке.
 */
export function normalizeThresholds(t?: Partial<ExplosionThresholds>): ExplosionThresholds {
  const d = DEFAULT_EXPLOSION_THRESHOLDS;
  const lethal = t?.lethal && t.lethal > 0 ? t.lethal : d.lethal;
  const heavy  = Math.min(t?.heavy  && t.heavy  > 0 ? t.heavy  : d.heavy,  lethal);
  const medium = Math.min(t?.medium && t.medium > 0 ? t.medium : d.medium, heavy);
  const light  = Math.min(t?.light  && t.light  > 0 ? t.light  : d.light,  medium);
  const safeLimit = Math.min(t?.safeLimit && t.safeLimit > 0 ? t.safeLimit : d.safeLimit, light);
  return { lethal, heavy, medium, light, safeLimit };
}

export function hazardLevelWith(dP: number, t: ExplosionThresholds): ExplosionZone["hazardLevel"] {
  if (dP >= t.lethal) return "lethal";
  if (dP >= t.heavy)  return "heavy";
  if (dP >= t.medium) return "medium";
  if (dP >= t.light)  return "light";
  return "safe";
}

function hazardLevel(dP: number): ExplosionZone["hazardLevel"] {
  return hazardLevelWith(dP, DEFAULT_EXPLOSION_THRESHOLDS);
}

/** Радиус, при котором давление падает до порогового значения */
function radiusAtPressure(targetP_kPa: number, q_tnt: number, wallFactor: number): number {
  if (targetP_kPa <= 0 || q_tnt <= 0) return 0;
  // Бинарный поиск радиуса
  // Верхний предел 50 км: в канальной модели волна уходит на километры,
  // и прежние 5000 м обрезали радиус зоны на этом значении.
  let lo = 0.1, hi = 50000;
  for (let i = 0; i < 60; i++) {
    const mid = (lo + hi) / 2;
    const dP = sadovskyDeltaP(mid, q_tnt) * wallFactor;
    if (dP > targetP_kPa) lo = mid; else hi = mid;
  }
  return Math.round((lo + hi) / 2);
}

/**
 * Результат «взрыва не было»: все параметры нулевые, зоны отсутствуют.
 *
 * Возвращается, когда заряд нулевой или смесь вне пределов взрываемости.
 * Массив zones намеренно ПУСТОЙ, а не с нулевыми радиусами: потребители
 * рисуют окружность по zones[i].radius_m, и зона радиусом 0 всё равно даёт
 * точку и строку в легенде, будто поражение есть.
 */
function emptyExplosionResult(
  th: ExplosionThresholds,
  reason: string,
  log: string[],
  warnings: string[],
): ExplosionResult {
  return {
    q_tnt_kg: 0,
    maxDeltaP_kPa: 0,
    maxImpulse_Pas: 0,
    waveFrontSpeed_ms: 0,
    minValidRadius_m: 0,
    thresholds: th,
    noExplosion: true,
    noExplosionReason: reason,
    zones: [],
    pressureAtDistance: () => 0,
    impulseAtDistance: () => 0,
    log,
    warnings,
  };
}

// ─── Главная функция расчёта ──────────────────────────────────────────────────
export function calcExplosion(params: ExplosionParams): ExplosionResult {
  const log: string[] = [];
  const warnings: string[] = [];
  // Пороги зон — из справочника; при их отсутствии берутся значения
  // по умолчанию. normalizeThresholds следит за убыванием ряда.
  const th = normalizeThresholds(params.thresholds);

  // 1. Тротиловый эквивалент
  let q_tnt = 0;
  // Причина, по которой взрыва не происходит. Заполняется ниже; если она
  // задана — расчёт прекращается и возвращается нулевой результат.
  let noExplosionReason = "";
  // Удельная энергия смеси, МДж/м³ — заполняется в газовой ветке и через
  // неё вид газа, концентрация и Z влияют на ΔP₀ (см. gasInitialPressure).
  let gasEv = 0;

  // Длина загазованного участка и объём смеси.
  // ГЛАВНОЕ: объём считается как L × S выработки, а не берётся буквально из
  // поля «Объём смеси». В «Аэросети» вводится именно ДЛИНА участка, и при
  // сечении 12 м² «100 м выработки» — это 1200 м³, а не 100. Старая трактовка
  // занижала энергию ровно во столько раз, сколько метров в сечении.
  const gasZoneLen = params.gasZoneLength_m && params.gasZoneLength_m > 0
    ? params.gasZoneLength_m : 0;
  const gasVolume = gasZoneLen > 0 && params.excavationArea_m2 > 0
    ? gasZoneLen * params.excavationArea_m2
    : params.gasVolume_m3;

  if (params.sourceType === "gas") {
    const gas = GAS_TYPES.find(g => g.id === params.gasId) ?? GAS_TYPES[0];
    const conc = params.gasConcentration;
    const u = concUnitLabel(gas.unit);
    // ПРОВЕРКА ВЗРЫВАЕМОСТИ — она прекращает расчёт, а не просто
    // предупреждает. Вне пределов НПВ/ВПВ смесь физически не детонирует:
    // раньше предупреждение выводилось, но энергия всё равно считалась,
    // и для 1 % метана (вдвое ниже НПВ) программа рисовала зоны поражения.
    if (conc <= 0) {
      noExplosionReason = `Концентрация ${gas.name.toLowerCase()} равна нулю — горючего нет, взрыв невозможен`;
    } else if (conc < gas.lowerLimit) {
      noExplosionReason = `Концентрация ${conc} ${u} ниже НПВ (${gas.lowerLimit} ${u}) — смесь не взрывоопасна, зоны поражения не образуются`;
    } else if (conc > gas.upperLimit) {
      noExplosionReason = `Концентрация ${conc} ${u} выше ВПВ (${gas.upperLimit} ${u}) — смесь не взрывоопасна, зоны поражения не образуются`;
    } else if (gasVolume <= 0) {
      noExplosionReason = "Объём взрывоопасной смеси равен нулю — взрыв невозможен";
    }
    // Обогащённая смесь: горючего больше стехиометрии — не хватает кислорода.
    // Энергия ограничена окислителем, поэтому сверх стехиометрии в расчёт
    // идёт стехиометрическая концентрация, а не заданная.
    const effectiveConc = Math.min(conc, gas.stoichConc);
    const z = params.zParticipation && params.zParticipation > 0 ? params.zParticipation : Z_DEFAULT;
    q_tnt = gasToTnt(gas, gasVolume, effectiveConc, z);
    // Удельная энергия смеси — через неё вид газа, концентрация и Z влияют
    // на начальное давление ΔP₀, а значит и на зоны поражения.
    gasEv = gasEnergyDensity(gas, conc, z);
    if (gasZoneLen > 0) {
      log.push(`Загазованный участок: длина ${gasZoneLen} м × сечение ${params.excavationArea_m2} м² = ${Math.round(gasVolume)} м³ смеси`);
    }
    log.push(`${gas.unit === "g/m3" ? "Пыль" : "Газ"}: ${gas.name}, объём смеси: ${Math.round(gasVolume)} м³, концентрация: ${conc} ${u}`);
    if (effectiveConc < conc) {
      log.push(`Смесь обогащённая: в расчёт принята стехиометрическая концентрация ${effectiveConc} ${u} (энергия ограничена кислородом)`);
    }
    log.push(`Коэффициент участия Z (Методика №415): ${z}`);
    log.push(`Тротиловый эквивалент: Q_tnt = ${Math.round(q_tnt * 100) / 100} кг ТНТ`);
  } else {
    const expl = EXPLOSIVE_TYPES.find(e => e.id === params.explosiveId) ?? EXPLOSIVE_TYPES[0];
    const mass = params.explosiveMass_kg;
    // Нулевая (или не заданная) масса заряда — взрывать нечего.
    if (!Number.isFinite(mass) || mass <= 0) {
      noExplosionReason = "Масса взрывчатого вещества равна нулю — взрыв невозможен";
    }
    q_tnt = massToTnt(expl, mass);
    log.push(`ВВ: ${expl.name}, масса: ${params.explosiveMass_kg} кг, Q_уд = ${expl.qSpec} кДж/кг`);
    log.push(`Тротиловый эквивалент: k = Q_уд / Q_ТНТ = ${expl.qSpec} / ${Q_TNT} = ${tntEquivalent(expl)}`);
    log.push(`Тротиловый эквивалент: Q_tnt = ${Math.round(q_tnt * 100) / 100} кг ТНТ`);
  }

  // Заряда нет ни по массе, ни по энергии — дальше считать нечего.
  // Раньше здесь подставлялось q_tnt = 0.001 кг «чтобы формулы не делились
  // на ноль», и из этой выдуманной сотой грамма вырастали настоящие зоны
  // поражения с ненулевыми радиусами. Теперь расчёт честно возвращает нули.
  if (!noExplosionReason && (!Number.isFinite(q_tnt) || q_tnt <= 0)) {
    noExplosionReason = "Тротиловый эквивалент равен нулю — взрыв невозможен";
  }

  if (noExplosionReason) {
    warnings.push(`⚠ ${noExplosionReason}`);
    log.push(`Взрыв не происходит: ${noExplosionReason.toLowerCase()}`);
    log.push("Зоны поражения не рассчитываются, радиусы приняты равными нулю");
    return emptyExplosionResult(th, noExplosionReason, log, warnings);
  }

  // ── ГАЗ И ПЫЛЬ ПО МЕТОДИКЕ ВГСЧ (по умолчанию) ─────────────────────────────
  if (params.sourceType === "gas" && (params.gasMethod ?? "vgsch") === "vgsch") {
    return calcVgsch(params, th, gasZoneLen, gasVolume, q_tnt, log, warnings);
  }

  // Граница применимости формулы для этого заряда, м (r̄ = 1).
  // Ниже её параметры волны методикой не определяются.
  const rMinValid = minValidRadius(q_tnt);

  // 2. Модель распространения.
  // По умолчанию — КАНАЛЬНАЯ: ближняя зона сферическая (Садовский), дальняя
  // идёт по выработке с затуханием на трении. Прежний wallFactor при этом
  // НЕ применяется: он был грубой заменой канализирования постоянным
  // множителем, и вместе с канальной моделью эффект учитывался бы дважды —
  // ровно та же ошибка, из-за которой был удалён режим «ФНиП №494».
  const channelMode = params.channelMode !== false;
  const channel: ChannelParams = {
    area_m2: params.excavationArea_m2,
    perimeter_m: params.excavationPerimeter_m,
    lambda: params.channelLambda,
  };
  const wallFactor = (!channelMode && params.considerWalls)
    ? wallReflectionFactor(params.excavationArea_m2)
    : 1.0;

  const rTr  = channelMode ? Math.max(transitionRadius(channel.area_m2), rMinValid) : 0;
  const beta = channelMode ? channelDecay(channel) : 0;

  // ГАЗ — плоская волна от протяжённого загазованного участка.
  // Сферическая ближняя зона для газа не применяется: очаг занимает всё
  // сечение выработки, поэтому волна плоская с самого начала.
  const gasSource: GasSourceParams | undefined = (() => {
    if (!channelMode || params.sourceType !== "gas") return undefined;
    const zoneLen = gasZoneLen > 0
      ? gasZoneLen
      // Длина не задана — восстанавливаем её из объёма и сечения
      : (params.excavationArea_m2 > 0 ? gasVolume / params.excavationArea_m2 : 0);
    // ΔP₀ задано вручную — используем его; иначе считаем по длине участка
    const manual = params.gasInitialPressure_kPa && params.gasInitialPressure_kPa > 0;
    return {
      zoneLength_m: zoneLen,
      initialPressure_kPa: manual
        ? params.gasInitialPressure_kPa!
        : gasInitialPressure(zoneLen, gasEv),
    };
  })();

  if (gasSource) {
    const auto = !(params.gasInitialPressure_kPa && params.gasInitialPressure_kPa > 0);
    log.push(`Модель источника: протяжённый загазованный участок (плоская волна, как в «Аэросети»)`);
    log.push(`Длина участка: ${Math.round(gasSource.zoneLength_m * 10) / 10} м`);
    if (auto) {
      const rel = Math.round((gasEv / GAS_EV_REF) * 1000) / 1000;
      log.push(`Удельная энергия смеси: ${Math.round(gasEv * 1000) / 1000} МДж/м³ (эталон метан 9,5 % при Z=0,5: ${GAS_EV_REF}; отношение ${rel})`);
      log.push(`Начальное давление ΔP₀ = ${gasSource.initialPressure_kPa} кПа (${GAS_P0_COEF}·L^${GAS_P0_EXP}·E_v/E_ref)`);
    } else {
      log.push(`Начальное давление ΔP₀ = ${gasSource.initialPressure_kPa} кПа (задано вручную)`);
    }
  }

  if (channelMode) {
    const dg = hydraulicDiameter(channel.area_m2, channel.perimeter_m);
    log.push(gasSource
      ? `Модель распространения: канальная (плоская волна по выработке)`
      : `Модель распространения: канальная (ближняя зона — Садовский, дальняя — выработка)`);
    log.push(`Сечение S = ${channel.area_m2} м², гидравлический диаметр d = ${Math.round(dg * 100) / 100} м`);
    log.push(`Коэффициент сопротивления λ = ${channel.lambda ?? LAMBDA_DEFAULT}`);
    // Переход сфера → канал есть только у компактного заряда (ВВ).
    if (!gasSource) log.push(`Переход сфера → канал: r = ${Math.round(rTr * 10) / 10} м`);
    log.push(`Погонное затухание β = λ/(2d) = ${beta.toExponential(3)} 1/м`);
  } else if (params.considerWalls) {
    log.push(`Модель распространения: сферическая, коэффициент стенок k = ${wallFactor}`);
  }

  // 3. Функции давления и импульса.
  // Обе ограничены снизу границей применимости (см. sadovskyDeltaP):
  // внутри r̄ = 1 возвращается значение на границе, а не расходящееся.
  // r = 0 (точка установки очага) — тоже максимум, а не ноль: раньше
  // ветка `r_m <= 0` давала 0 кПа, и эпицентр взрыва попадал в «безопасно».
  const pressureAtDistance = (r: number) => {
    if (gasSource) return gasChannelPressureAt(r, gasSource, channel);
    if (channelMode) return channelPressureAt(r, q_tnt, channel);
    const dP = sadovskyDeltaP(Math.max(r, rMinValid), q_tnt);
    return Math.round(dP * wallFactor * 10) / 10;
  };

  const impulseAtDistance = (r: number) => {
    if (gasSource) return gasChannelImpulseAt(r, gasSource, channel);
    if (channelMode) return channelImpulseAt(r, q_tnt, channel);
    const i = sadovskyImpulse(Math.max(r, rMinValid), q_tnt);
    return Math.round(i * wallFactor * 10) / 10;
  };

  // 4. Максимальные параметры — на ГРАНИЦЕ ПРИМЕНИМОСТИ формулы (r̄ = 1).
  // Раньше здесь стояло r = 1 м независимо от массы заряда. Для 97 кг ТНТ
  // это r̄ = 0.22, то есть глубоко внутри зоны, где формула Садовского уже
  // не работает: получалось 74 000 кПа и скорость фронта 8 500 м/с.
  // Ближе к заряду параметры волны этой методикой не определяются.
  // Для газа максимум — это начальное давление в самом загазованном участке:
  // граница применимости Садовского здесь ни при чём, формула не используется.
  const rMin = gasSource ? 0 : rMinValid;
  const maxDeltaP = pressureAtDistance(rMin);
  const maxImpulse = impulseAtDistance(rMin);
  const waveFrontSpeed_ms = waveFrontSpeed(maxDeltaP);
  // Длительность фазы сжатия — та же точка, что и для maxImpulse.
  // Без неё импульсы двух веток выглядят несопоставимо.
  const phaseDuration_ms = Math.round(
    (gasSource ? gasPhaseDuration(gasSource) : tntPhaseDuration(rMin, q_tnt)) * 1000 * 10,
  ) / 10;

  if (gasSource) {
    log.push("Методика: плоская волна от загазованного участка, Q_тнт по Методике №415 (справочно)");
    log.push(`Максимальное давление (внутри участка): ΔP = ${maxDeltaP} кПа`);
    log.push(`Длительность фазы сжатия: τ = (L/2)/c_прод = ${phaseDuration_ms} мс (c_прод = ${C_PRODUCTS} м/с)`);
  } else {
    log.push("Методика: газодинамическая (Садовский), Q_тнт по Методике №415");
    log.push(`Граница применимости формулы: r̄ = 1, то есть r = ${rMin} м`);
    log.push(`Максимальное давление во фронте (r = ${rMin} м): ΔP = ${maxDeltaP} кПа`);
    log.push(`Длительность фазы сжатия: τ = i/ΔP = ${phaseDuration_ms} мс`);
  }
  log.push(`Импульс: i = ΔP·τ = ${maxImpulse} Па·с`);
  log.push(`Скорость фронта: D = ${waveFrontSpeed_ms} м/с`);

  // 5. Зоны поражения — строятся из порогов справочника, а не из
  // зашитых чисел: ряд порогов в разных документах различается.
  const zoneDefs: Array<{
    name: string; level: ExplosionZone["hazardLevel"]; from: number; to: number | null; what: string;
  }> = [
    { name: "Летальная",         level: "lethal", from: th.lethal, to: null,      what: "летальный исход, полное разрушение" },
    { name: "Тяжёлые поражения", level: "heavy",  from: th.heavy,  to: th.lethal, what: "тяжёлые травмы, обрушение конструкций" },
    { name: "Средние поражения", level: "medium", from: th.medium, to: th.heavy,  what: "средние травмы, повреждение оборудования" },
    { name: "Лёгкие поражения",  level: "light",  from: th.light,  to: th.medium, what: "контузии, звуковая травма, лёгкие повреждения" },
  ];

  // Радиус зоны: в канальном режиме это ДЛИНА ПУТИ ПО ВЫРАБОТКЕ, а не
  // радиус сферы. Именно поэтому значения получаются в сотни метров —
  // волна не рассеивается в объём, а идёт по каналу.
  const zoneReach = (p: number) => gasSource
    ? gasChannelDistanceAtPressure(p, gasSource, channel)
    : channelMode
      ? channelDistanceAtPressure(p, q_tnt, channel)
      : radiusAtPressure(p, q_tnt, wallFactor);

  const zones: ExplosionZone[] = zoneDefs.map(d => {
    const r = zoneReach(d.from);
    return {
      name: d.name,
      description: `ΔP ${d.to === null ? `> ${d.from}` : `${d.from}–${d.to}`} кПа — ${d.what}`,
      radius_m: r,
      deltaP_kPa: d.from,
      impulse_Pas: impulseAtDistance(r),
      hazardLevel: d.level,
    };
  });

  const rSafe = zoneReach(th.safeLimit);
  zones.push({
    name: "Безопасная зона",
    description: `ΔP < ${th.safeLimit} кПа — незначительное воздействие`,
    radius_m: rSafe,
    deltaP_kPa: th.safeLimit,
    impulse_Pas: impulseAtDistance(rSafe),
    hazardLevel: "safe",
  });

  zones.forEach(z => {
    log.push(`${z.name}: r = ${z.radius_m} м, ΔP = ${z.deltaP_kPa} кПа`);
  });

  return {
    q_tnt_kg: Math.round(q_tnt * 100) / 100,
    maxDeltaP_kPa: maxDeltaP,
    maxImpulse_Pas: maxImpulse,
    phaseDuration_ms,
    waveFrontSpeed_ms,
    minValidRadius_m: rMin,
    thresholds: th,
    channelMode,
    transitionRadius_m: channelMode ? Math.round(rTr * 10) / 10 : undefined,
    channelDecay_per_m: channelMode ? beta : undefined,
    channel: channelMode ? channel : undefined,
    gasSource,
    zones,
    pressureAtDistance,
    impulseAtDistance,
    log,
    warnings,
  };
}

/**
 * Расчёт взрыва газа/пыли по Методике ВГСЧ (Прил. 12 к Уставу ВГСЧ).
 *
 * Для одиночной выработки-очага: зона загазования → зона продуктов взрыва
 * (5V₀) → затухание УВВ по ф. (3). Местные сопротивления учитываются при
 * распространении по схеме (explosionModeRun / blastNetwork).
 */
function calcVgsch(
  params: ExplosionParams,
  th: ExplosionThresholds,
  gasZoneLen: number,
  gasVolume: number,
  q_tnt: number,
  log: string[],
  warnings: string[],
): ExplosionResult {
  const gas = GAS_TYPES.find(g => g.id === params.gasId) ?? GAS_TYPES[0];
  const area = params.excavationArea_m2 > 0 ? params.excavationArea_m2 : 12;
  const zoneLen = gasZoneLen > 0 ? gasZoneLen : gasVolume / area;
  const mode = combustionMode(params.combustionMode);
  // Энергия смеси относительно стехиометрической метановоздушной, для
  // которой составлены расчётные зависимости методики. Для других газов и
  // нестехиометрических смесей — пересчёт по теплоте сгорания.
  const z = 1; // коэффициент участия Z в методике ВГСЧ не применяется
  const ev = gasEnergyDensity(gas, params.gasConcentration, z);
  const evRef = gasEnergyDensity(GAS_TYPES[0], GAS_TYPES[0].stoichConc, z);
  const isDust = gas.unit === "g/m3";
  const energyRel = isDust ? 1 : (evRef > 0 ? ev / evRef : 1);
  const src = makeVgschSource({
    zoneLength_m: zoneLen,
    V0_m3: gasVolume,
    mode: mode.id,
    energyRel,
    dust: isDust || params.dustParticipation === true,
    area_m2: area,
    perimeter_m: params.excavationPerimeter_m,
    alpha: params.excavationAlpha,
  });
  const S = area;
  const P = src.perimeter_m;
  const pvLen = src.pvVolumePerSide_m3 / S;

  log.push("Методика: определение параметров УВВ при взрывах газов и пыли в горных выработках (Прил. 12 к Уставу ВГСЧ)");
  log.push(`Объём загазования V₀ = ${Math.round(src.V0_m3)} м³ (участок ${Math.round(zoneLen * 10) / 10} м × ${S} м²)`);
  if (energyRel !== 1) log.push(`Энергия смеси относительно стехиометрической метановоздушной: ${Math.round(energyRel * 1000) / 1000}`);
  log.push(`Энергия взрыва Ен = ρ₀·gv·V₀${src.dustFactor > 1 ? "·1,3 (участие пыли)" : ""} = ${Math.round(src.En_MJ)} МДж`);
  log.push(`Вид взрыва (табл. 2): ${mode.label}, μ = ${mode.mu}`);
  log.push(`Начальное давление УВВ в месте отрыва от ПВ, ф. (2): ΔPн = ${Math.round(src.dPn_kPa)} кПа (${Math.round(src.dPn_kPa) / 1000} МПа)`);
  log.push(`Давление в зоне загазования: ${Math.round(src.dPz_kPa)} кПа${mode.id === "detonation" ? ` (${VGSCH_ZONE1_KPA / 1000} МПа)` : " (пересчитано на вид взрыва)"}`);
  log.push(`Зона продуктов взрыва: ${VGSCH_PV_FACTOR}V₀ = ${Math.round(VGSCH_PV_FACTOR * src.V0_m3)} м³, по ${Math.round(pvLen)} м в каждую сторону за пределами загазования`);
  log.push(`Периметр П = ${Math.round(P * 100) / 100} м${params.excavationPerimeter_m ? "" : " (оценка 4√S)"}, Кз = ${src.kz} (табл. 3 по α = ${params.excavationAlpha ?? "—"}·10⁻⁴)`);
  log.push(`Затухание УВВ, ф. (3): ΔPх = ΔPн·exp(−П·x·Кз/F), П·Кз/F = ${(src.kz * P / S).toExponential(3)} 1/м`);

  const pressureAtDistance = (r: number) => vgschPressureAt(r, src);
  const impulseAtDistance = (r: number) => vgschImpulseAt(r, src);
  const maxDeltaP = pressureAtDistance(0);
  const maxImpulse = impulseAtDistance(0);
  const phaseDuration_ms = Math.round(src.phase_s * 1000 * 10) / 10;
  log.push(`Время действия θ ≈ (L/2)/c_прод = ${phaseDuration_ms} мс; импульс i = ΔP·θ/2 = ${maxImpulse} Н·с/м²`);

  const zoneDefs: Array<{ name: string; level: ExplosionZone["hazardLevel"]; from: number; to: number | null; what: string }> = [
    { name: "Летальная",         level: "lethal", from: th.lethal, to: null,      what: "летальный исход, полное разрушение" },
    { name: "Тяжёлые поражения", level: "heavy",  from: th.heavy,  to: th.lethal, what: "тяжёлые травмы, обрушение конструкций" },
    { name: "Средние поражения", level: "medium", from: th.medium, to: th.heavy,  what: "средние травмы, повреждение оборудования" },
    { name: "Лёгкие поражения",  level: "light",  from: th.light,  to: th.medium, what: "контузии, звуковая травма, лёгкие повреждения" },
  ];
  const zones: ExplosionZone[] = zoneDefs.map(d => {
    const r = vgschDistanceAtPressure(d.from, src);
    return {
      name: d.name,
      description: `ΔP ${d.to === null ? `> ${d.from}` : `${d.from}–${d.to}`} кПа — ${d.what}`,
      radius_m: r, deltaP_kPa: d.from, impulse_Pas: impulseAtDistance(r), hazardLevel: d.level,
    };
  });
  const rSafe = vgschDistanceAtPressure(th.safeLimit, src);
  zones.push({
    name: "Безопасная зона",
    description: `ΔP < ${th.safeLimit} кПа — безопасно для человека`,
    radius_m: rSafe, deltaP_kPa: th.safeLimit, impulse_Pas: impulseAtDistance(rSafe), hazardLevel: "safe",
  });
  zones.forEach(zz => log.push(`${zz.name}: ${zz.radius_m} м от центра очага, ΔP = ${zz.deltaP_kPa} кПа`));
  log.push("Расстояния — по прямой выработке-очагу без местных сопротивлений; по схеме волна ведётся с учётом сопряжений и поворотов (табл. 5)");
  if (th.safeLimit < VGSCH_SAFE_KPA) {
    log.push(`Безопасное для человека давление по методике — ${VGSCH_SAFE_KPA} кПа, безопасный импульс — ${VGSCH_SAFE_IMPULSE} Н·с/м²`);
  }
  if (src.dPn_kPa <= th.light) {
    warnings.push("Начальное давление УВВ ниже порога лёгких поражений — проверьте вид взрыва и объём загазования");
  }

  return {
    q_tnt_kg: Math.round(q_tnt * 100) / 100,
    maxDeltaP_kPa: maxDeltaP,
    maxImpulse_Pas: maxImpulse,
    phaseDuration_ms,
    waveFrontSpeed_ms: waveFrontSpeed(src.dPn_kPa),
    minValidRadius_m: 0,
    thresholds: th,
    channelMode: true,
    transitionRadius_m: 0,
    channelDecay_per_m: src.kz * P / S,
    channel: { area_m2: S, perimeter_m: P },
    vgsch: src,
    zones,
    pressureAtDistance,
    impulseAtDistance,
    log,
    warnings,
  };
}

/** Уровень опасности по давлению (для окраски ветвей) */
export function explosionHazardLevel(deltaP_kPa: number): ExplosionZone["hazardLevel"] {
  return hazardLevel(deltaP_kPa);
}

/**
 * Цвет ветви по уровню поражения — ЕДИНСТВЕННЫЙ источник правды.
 * ВАЖНО: только hex. Эти цвета уходят в ctx.strokeStyle холста, а canvas
 * не понимает запись var(--...) — при невалидном цвете присваивание молча
 * игнорируется и линия рисуется предыдущим цветом контекста.
 */
export const EXPLOSION_HAZARD_COLORS: Record<ExplosionZone["hazardLevel"], string> = {
  lethal:  "#7c1010",
  heavy:   "#dc2626",
  medium:  "#f97316",
  light:   "#fbbf24",
  safe:    "#22c55e",
};

/**
 * Зона поражения (цвет + уровень) по избыточному давлению.
 * Пороги передаются из справочника — иначе окраска схемы разошлась бы
 * с радиусами зон, посчитанными по пользовательскому ряду.
 */
export function explosionZoneColor(
  deltaP_kPa: number,
  thresholds?: ExplosionThresholds,
): { color: string; hazardLevel: ExplosionZone["hazardLevel"] } {
  const level = hazardLevelWith(deltaP_kPa, thresholds ?? DEFAULT_EXPLOSION_THRESHOLDS);
  return { color: EXPLOSION_HAZARD_COLORS[level], hazardLevel: level };
}