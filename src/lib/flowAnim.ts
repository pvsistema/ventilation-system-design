// ─────────────────────────────────────────────────────────────────────────────
// flowAnim.ts — ЕДИНЫЙ ЗАКОН ДВИЖЕНИЯ СТРЕЛОК ВОЗДУХА.
//
// Стрелки направления воздуха рисуют два разных движка: чертёж (Canvas 2D,
// canvasRenderer) и модель (three.js, mineArrows). До появления этого модуля у
// каждого был свой закон скорости и своя точка отсчёта времени: на чертеже
// стрелка бежала «22 пикселя в секунду на каждый метр в секунду воздуха»
// независимо от масштаба, в объёме — по натурной скорости в координатах сцены.
// В итоге одна и та же выработка в двух режимах показывала разный темп, а при
// переключении режима стрелки прыгали.
//
// Здесь один закон и одни часы на оба режима:
//   • скорость бега считается в МЕТРАХ сцены в секунду от натурной скорости
//     воздуха — значит в обоих режимах она пропорциональна одному и тому же
//     числу, и сравнение выработок между собой остаётся правдивым;
//   • время отсчитывается от общей точки, поэтому фаза движения не сбивается
//     при переходе «Чертёж ↔ Модель».
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Пределы натурной скорости воздуха, м/с, в которых считается бег стрелки.
 *
 * Снизу — чтобы стрелка в слабо проветриваемой выработке не замирала совсем и
 * было видно, что воздух всё-таки идёт. Сверху — чтобы в стволе с сильной
 * струёй стрелки не превращались в мельтешение, за которым не уследить.
 */
export const FLOW_V_MIN = 0.25;
export const FLOW_V_MAX = 20;

/**
 * Во сколько раз бег стрелок быстрее натурной скорости воздуха.
 *
 * Один к одному было бы честно, но нечитаемо: в масштабе плана стрелка шла бы
 * от узла до узла десятки секунд. Множитель общий для всех выработок и для
 * обоих режимов, поэтому сравнение выработок между собой не врёт.
 */
export const FLOW_SPEED_K = 3;

/**
 * Скорость бега стрелки в МЕТРАХ РУДНИКА в секунду.
 *
 * Модуль у скорости обязателен: при опрокидывании струи velocity отрицательна,
 * и без модуля стрелка упиралась бы в нижний предел независимо от реального
 * расхода. Само направление задаётся не здесь, а знаком расхода.
 */
export function arrowSpeedMps(velocity: number | undefined, animSpeed: number | undefined): number {
  const v = Math.min(FLOW_V_MAX, Math.max(FLOW_V_MIN, Math.abs(velocity ?? 0)));
  return v * FLOW_SPEED_K * Math.max(0.1, animSpeed ?? 1);
}

/**
 * Пределы скорости на ЭКРАНЕ, пикселей в секунду.
 *
 * Скорость по закону выше пропорциональна масштабу показа: на общем плане
 * рудника стрелка ползла бы по пикселю в секунду, а при сильном приближении
 * проскакивала бы выработку за кадр. Пределы не дают ни того, ни другого.
 */
export const FLOW_PX_MIN = 10;
export const FLOW_PX_MAX = 450;

// ─────────────────────────────────────────────────────────────────────────────
// ПРОПОРЦИИ СТРЕЛКИ — ДОЛИ ТОЛЩИНЫ ВЫРАБОТКИ.
//
// Стрелку рисуют три места: бегущая анимация и статичный указатель в
// canvasRenderer, плюс оверлей условных обозначений (TopoCanvasFlowArrows).
// Раньше числа были вписаны в каждом отдельно, и правка в одном месте молча
// расходилась с остальными: на одной и той же выработке анимированная стрелка
// и статичная оказывались разной ширины.
//
// Считаются от w — толщины выработки на экране, поэтому стрелка масштабируется
// вместе со схемой и в тонкой сбойке не выглядит так же, как в стволе.
// ─────────────────────────────────────────────────────────────────────────────

/** Длина наконечника. */
export const ARROW_TIP_H = 2.2;

/**
 * ПОЛУширина наконечника.
 *
 * Было 0.5 — наконечник ровно во всю выработку, из-за чего он смотрелся
 * пробкой, перекрывающей сечение, и налезал на кромки линии. Теперь заметно
 * уже её: стрелка идёт ВНУТРИ выработки, а не вместо неё.
 */
export const ARROW_TIP_W = 0.34;

/** Длина хвостика. */
export const ARROW_TAIL_LEN = 3.0;

/** Толщина хвостика. */
export const ARROW_TAIL_W = 0.15;

/**
 * Общая точка отсчёта времени анимации.
 *
 * Считаем от загрузки модуля, а не от абсолютного времени: большие числа в
 * вершинном шейдере теряют точность, и через несколько часов работы движение
 * начинает дёргаться.
 */
const EPOCH = typeof performance !== "undefined" ? performance.now() : 0;

/** Время анимации в секундах — одно на чертёж и на модель. */
export function flowTime(): number {
  return (performance.now() - EPOCH) / 1000;
}