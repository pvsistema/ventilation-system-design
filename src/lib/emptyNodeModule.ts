// Заглушка модуля «node:module» для браузерной сборки.
//
// Библиотека чтения чертежей DWG (libredwg-web) собрана сразу для двух сред:
// браузера и Node. Внутри неё есть ветка для Node, которая запрашивает
// «node:module», и сборщик из-за этого печатал предупреждение
// «Module "node:module" has been externalized for browser compatibility».
//
// В нашей программе эта ветка не выполняется никогда: и десктоп, и сайт
// работают в браузерном движке, где библиотека сама выбирает браузерный путь
// (она проверяет наличие process.versions.node). Поэтому подставляем пустую
// заглушку: предупреждение при сборке исчезает, поведение не меняется.
//
// Если заглушку всё же вызовут — значит, код случайно пошёл по «серверной»
// ветке, и молчать нельзя: понятная ошибка лучше, чем непонятный сбой позже.
export function createRequire(): never {
  throw new Error(
    "createRequire недоступен в браузере: код пошёл по серверной ветке библиотеки",
  );
}

export default { createRequire };
