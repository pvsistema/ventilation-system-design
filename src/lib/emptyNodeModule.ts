// ─────────────────────────────────────────────────────────────────────────────
// emptyNodeModule.ts — заглушка встроенного модуля Node.js «node:module».
//
// ЗАЧЕМ ЭТОТ ФАЙЛ.
// Библиотека чтения чертежей DWG (@mlightcad/libredwg-web) собрана сразу для
// двух сред — браузера и Node.js. В самом её начале стоит развилка:
//
//     if (ENVIRONMENT_IS_NODE) {
//         const { createRequire } = await import("node:module");
//         var require = createRequire(import.meta.url);
//     }
//
// В программе эта ветка НИКОГДА не выполняется: и десктоп (WebView2), и сайт
// работают в браузерном движке, где библиотека сама уходит в браузерный путь —
// чертежи читаются через fetch и WebAssembly. Но сборщик разбирает код целиком,
// не зная, какая ветка отработает, и обязан чем-то разрешить «node:module».
//
// Поэтому в vite.config.desktop.ts стоит подмена этого имени на данный файл.
// Без него сборка десктопа падала с ошибкой:
//     [UNLOADABLE_DEPENDENCY] Could not load src/lib/emptyNodeModule.ts
//     — Не удается найти указанный файл
//
// ВАЖНО: заглушка обязана отдавать именно createRequire, а не пустой объект.
// Разбор `const { createRequire } = await import(...)` происходит до проверки
// условия, и отсутствие имени уронило бы сборку уже по другой причине.
// Возвращаемая функция при вызове честно сообщает об ошибке: если она всё же
// когда-то выполнится, мы увидим внятное сообщение вместо «undefined is not a
// function».
// ─────────────────────────────────────────────────────────────────────────────

/** Сообщение об ошибке — общее для всех заглушённых точек входа. */
const NOT_AVAILABLE =
  "Модуль Node.js «node:module» недоступен: программа работает в браузерном " +
  "движке. Эта ветка кода не должна выполняться — чтение чертежей DWG идёт " +
  "браузерным путём.";

/**
 * Заглушка Node-функции createRequire.
 * В браузере вызываться не должна; если вызвана — падаем с понятным текстом.
 */
export function createRequire(_url?: string | URL): never {
  throw new Error(NOT_AVAILABLE);
}

/** Заглушка Module — некоторые сборки обращаются к нему как к свойству. */
export const Module = undefined;

/** Заглушка builtinModules — список встроенных модулей Node, в браузере пуст. */
export const builtinModules: string[] = [];

export default { createRequire, Module, builtinModules };
