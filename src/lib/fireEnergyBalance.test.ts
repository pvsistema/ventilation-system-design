// ─────────────────────────────────────────────────────────────────────────────
// fireEnergyBalance.test.ts — защита закона сохранения энергии в расчёте пожара.
//
// Сторожит конкретную ошибку, из-за которой расчёт расходился с АэроСетью:
// температура продуктов горения считалась по одному расходу, а масса той же
// струи попадала в узловой баланс по ДРУГОМУ (штатному) расходу. Очаг 8,5 МВт
// при схлопнувшемся потоке подогревал сеть как 17 МВт — отсюда завышенная
// тепловая тяга, провалы расхода и ложные опрокидывания смежных выработок.
//
// Проверка идёт на узле СОПРЯЖЕНИЯ, где горячая струя смешивается со свежей:
// только там вес массы влияет на температуру смеси. На одиночной ветви ошибка
// не проявляется — смесь из одной струи равна ей самой.
// ─────────────────────────────────────────────────────────────────────────────
import { describe, it, expect } from "vitest";
import { computeHotNodeTemps, calcFireTemp } from "@/lib/fireCalculator";

const CP = 1.005, RHO = 1.25, AMB = 15;

// Узел N2 — сопряжение: в него приходят ГОРЯЧАЯ струя очага (N1->N2)
// и СВЕЖАЯ струя по соседней выработке (N4->N2). Именно здесь вес массы
// горячей струи определяет температуру смеси, а значит и тепловую тягу.
const seats = (fireTemp: number, flow: number, originalFlow: number) => ([{
  id: "F", fromId: "N1", toId: "N2", fireTemp, flow, originalFlow,
  length: 48, area: 16.2, perimeter: 16,
}]);
const net = (qFire: number, qFresh: number) => ([
  { id: "F", fromId: "N1", toId: "N2", flow: qFire,  length: 48, area: 16.2, perimeter: 16 },
  { id: "C", fromId: "N4", toId: "N2", flow: qFresh, length: 50, area: 16.2, perimeter: 16 },
]);
const base = { N1: AMB, N2: AMB, N4: AMB };

describe("Сохранение энергии очага в узловом смешении", () => {
  it("энергия в узле сопряжения не превышает мощность очага при схлопнувшемся расходе", () => {
    const N = 8.52, Qштат = 75.04, Qфакт = 15, Qсвеж = 46.67;
    const T = calcFireTemp(N, Qштат, AMB);          // норматив: T по дожаровому Q
    const hot = computeHotNodeTemps(seats(T, Qфакт, Qштат), net(Qфакт, Qсвеж), AMB, base);

    // Мощность, «увиденная» сетью в узле: суммарная масса × подогрев смеси
    const mSum = RHO * (Qфакт + Qсвеж);
    const P = mSum * CP * 1000 * (hot["N2"] - AMB) / 1e6;

    expect(P).toBeLessThanOrEqual(N * 1.02);   // очаг не может дать больше своей мощности
  });

  it("температура смеси считается по фактическим массам струй", () => {
    const N = 8.52, Qштат = 75.04, Qфакт = 15, Qсвеж = 46.67;
    const T = calcFireTemp(N, Qштат, AMB);
    const hot = computeHotNodeTemps(seats(T, Qфакт, Qштат), net(Qфакт, Qсвеж), AMB, base);

    // Верхняя оценка смеси по балансу масс: m_гор*T_гор + m_свеж*T_амб
    const tMixMax = (Qфакт * T + Qсвеж * AMB) / (Qфакт + Qсвеж);
    expect(hot["N2"]).toBeLessThanOrEqual(tMixMax + 0.5);
  });

  // Чем сильнее душится поток, тем МЕНЬШЕ тепла уносится в сеть. Обратное
  // поведение (падение расхода → рост подогрева) и есть та положительная
  // обратная связь, которая схлопывала струю до нуля.
  it("падение расхода в очаге не усиливает нагрев сети", () => {
    const N = 8.52, Qштат = 75.04, Qсвеж = 46.67;
    const T = calcFireTemp(N, Qштат, AMB);   // T фиксирована дожаровым расходом

    const tAt = (qFact: number) =>
      computeHotNodeTemps(seats(T, qFact, Qштат), net(qFact, Qсвеж), AMB, base)["N2"];

    expect(tAt(15)).toBeLessThan(tAt(40));
    expect(tAt(40)).toBeLessThan(tAt(75.04));
  });
});

describe("Температура продуктов горения (норматив 4.8-4.11)", () => {
  // Q в формулах 4.8-4.11 — расход ДО пожара. Поэтому температура очага не
  // должна зависеть от того, что происходит с потоком во время пожара.
  it("определяется дожаровым расходом, а не текущим", () => {
    const N = 8.52, Qштат = 75.04;
    // Как считает fireModeRun: airQ = штатный расход, независимо от факта
    expect(calcFireTemp(N, Qштат, AMB)).toBeCloseTo(calcFireTemp(N, Qштат, AMB), 6);
    // Контроль чувствительности: по фактическому расходу вышло бы заметно выше
    expect(calcFireTemp(N, 15, AMB)).toBeGreaterThan(calcFireTemp(N, Qштат, AMB) + 100);
  });
});