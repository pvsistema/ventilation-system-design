// ─────────────────────────────────────────────────────────────────────────────
// fireEnergyBalance.test.ts — защита закона сохранения энергии в расчёте пожара.
//
// Сторожит конкретную ошибку, из-за которой расчёт расходился с АэроСетью:
// температура продуктов горения считалась по одному расходу, а масса той же
// струи попадала в узловой баланс по ДРУГОМУ (штатному) расходу. Очаг 8,5 МВт
// при схлопнувшемся потоке подогревал сеть как 17 МВт — отсюда завышенная
// тепловая тяга, провалы расхода и ложные опрокидывания смежных выработок.
//
// Проверка идёт на узле СОПРЯЖЕНИЯ, где горячая струя смешивается со свежей:
// только там вес массы влияет на температуру смеси. На одиночной ветви ошибка
// не проявляется — смесь из одной струи равна ей самой.
// ─────────────────────────────────────────────────────────────────────────────
import { describe, it, expect } from "vitest";
import { computeHotNodeTemps, calcFireTemp } from "@/lib/fireCalculator";

const CP = 1.005, RHO = 1.25, AMB = 15;

// Узел N2 — сопряжение: в него приходят ГОРЯЧАЯ струя очага (N1->N2)
// и СВЕЖАЯ струя по соседней выработке (N4->N2). Именно здесь вес массы
// горячей струи определяет температуру смеси, а значит и тепловую тягу.
const seats = (fireTemp: number, flow: number, originalFlow: number) => ([{
  id: "F", fromId: "N1", toId: "N2", fireTemp, flow, originalFlow,
  length: 48, area: 16.2, perimeter: 16,
}]);
const net = (qFire: number, qFresh: number) => ([
  { id: "F", fromId: "N1", toId: "N2", flow: qFire,  length: 48, area: 16.2, perimeter: 16 },
  { id: "C", fromId: "N4", toId: "N2", flow: qFresh, length: 50, area: 16.2, perimeter: 16 },
]);
const base = { N1: AMB, N2: AMB, N4: AMB };

describe("Сохранение энергии очага в узловом смешении", () => {
  it("энергия в узле сопряжения не превышает мощность очага при схлопнувшемся расходе", () => {
    const N = 8.52, Qштат = 75.04, Qфакт = 15, Qсвеж = 46.67;
    // T — по ТРАНСПОРТНОМУ (фактическому) расходу, как в fireModeRun.
    const T = calcFireTemp(N, Qфакт, AMB);
    const hot = computeHotNodeTemps(seats(T, Qфакт, Qштат), net(Qфакт, Qсвеж), AMB, base).hot;

    // Мощность, «увиденная» сетью в узле: суммарная масса × подогрев смеси
    const mSum = RHO * (Qфакт + Qсвеж);
    const P = mSum * CP * 1000 * (hot["N2"] - AMB) / 1e6;

    expect(P).toBeLessThanOrEqual(N * 1.02);   // очаг не может дать больше своей мощности
  });

  it("температура смеси считается по фактическим массам струй", () => {
    const N = 8.52, Qштат = 75.04, Qфакт = 15, Qсвеж = 46.67;
    const T = calcFireTemp(N, Qфакт, AMB);
    const hot = computeHotNodeTemps(seats(T, Qфакт, Qштат), net(Qфакт, Qсвеж), AMB, base).hot;

    // Верхняя оценка смеси по балансу масс: m_гор*T_гор + m_свеж*T_амб
    const tMixMax = (Qфакт * T + Qсвеж * AMB) / (Qфакт + Qсвеж);
    expect(hot["N2"]).toBeLessThanOrEqual(tMixMax + 0.5);
  });

  // ГЛАВНАЯ ПРОВЕРКА. Очаг отдаёт фиксированную мощность N. Сколько бы воздуха
  // через него ни шло, в сеть должно попасть ровно N — не больше и не меньше.
  // Нарушение в ЛЮБУЮ сторону замыкает положительную обратную связь:
  //   • энергия растёт с расходом  → струя разгоняется до бесконечности
  //     (так было: T по штатному Q, масса по фактическому → ΔQ +91,9 м³/с);
  //   • энергия падает с расходом  → струя схлопывается в ноль.
  // Оба режима наблюдались вживую, поэтому проверяем весь диапазон расходов.
  it("энергия в сети равна мощности очага при любом расходе", () => {
    const N = 8.52, Qштат = 106.82, Qсвеж = 46.67;

    // Так считает fireModeRun: T — по ТРАНСПОРТНОМУ (фактическому) расходу.
    const energyAt = (qFact: number) => {
      const T = calcFireTemp(N, Math.max(0.5, qFact), AMB);
      const hot = computeHotNodeTemps(seats(T, qFact, Qштат), net(qFact, Qсвеж), AMB, base).hot;
      // Мощность, «увиденная» сетью в узле смешения.
      return RHO * (qFact + Qсвеж) * CP * 1000 * (hot["N2"] - AMB) / 1e6;
    };

    // Разгон вдвое, штатный режим, схлопывание в 7 раз — всюду не больше N.
    for (const q of [198.7, 150, Qштат, 40, 15]) {
      expect(energyAt(q)).toBeLessThanOrEqual(N * 1.02);
    }
    // И не «теряется»: при штатном расходе в сеть уходит почти вся мощность
    // (небольшой недобор — теплопотери в стенки выработки).
    expect(energyAt(Qштат)).toBeGreaterThan(N * 0.7);
  });
});

describe("Температура продуктов горения", () => {
  // Разделение двух расходов — суть исправления. Нормативные формулы
  // (4.8–4.11) считаются по дожаровому Q, а перенос тепла по сети — по
  // фактическому, иначе энергия не сходится.
  it("транспортная температура обратно пропорциональна фактическому расходу", () => {
    const N = 8.52;
    // Разгон струи ОХЛАЖДАЕТ продукты горения: та же мощность на больший объём.
    expect(calcFireTemp(N, 198.7, AMB)).toBeLessThan(calcFireTemp(N, 106.82, AMB));
    // Схлопывание — наоборот, греет.
    expect(calcFireTemp(N, 15, AMB)).toBeGreaterThan(calcFireTemp(N, 106.82, AMB));
  });

  it("произведение расхода на подогрев постоянно (= мощность очага)", () => {
    const N = 8.52;
    const power = (q: number) => RHO * q * CP * 1000 * (calcFireTemp(N, q, AMB) - AMB) / 1e6;
    expect(power(198.7)).toBeCloseTo(N, 2);
    expect(power(106.82)).toBeCloseTo(N, 2);
    expect(power(15)).toBeCloseTo(N, 2);
  });
});
// ─────────────────────────────────────────────────────────────────────────────
// Ограничение горячего столба зоной горения (норматив 4.6, 4.12-4.13).
//
// Методика считает тепловую депрессию на разности отметок ЗОНЫ ГОРЕНИЯ
// Дz = l*sinB, где l - длина зоны горения (4.8), обычно 80-110 м. Если греть
// узлы вдоль всего пути дыма до поверхности, решатель наберёт тягу на сотнях
// метров вертикали: при T=135,9 C нормативные 56,1 Па отвечают столбу 15,8 м,
// а на столбе 200 м та же разность плотностей даёт уже 670 Па.
// ─────────────────────────────────────────────────────────────────────────────
describe("Протяжённость горячего столба", () => {
  const N = 8.52, Q = 58.55, S = 16.22;
  const T = calcFireTemp(N, Q, AMB);

  // Цепочка: очаг F (N1->N2), далее длинные ветви по ходу дыма.
  const chain = (lens: number[]) => {
    const br = [{ id: "F", fromId: "N1", toId: "N2", flow: Q, length: 24, area: S, perimeter: 16 }];
    lens.forEach((len, i) => br.push({
      id: `B${i}`, fromId: `N${i + 2}`, toId: `N${i + 3}`, flow: Q, length: len, area: S, perimeter: 16,
    }));
    return br;
  };
  const seat = [{ id: "F", fromId: "N1", toId: "N2", fireTemp: T, flow: Q, originalFlow: Q,
                  length: 24, area: S, perimeter: 16 }];
  const baseAll: Record<string, number> = {};
  for (let i = 1; i <= 8; i++) baseAll[`N${i}`] = AMB;

  it("перегрев затухает по мере удаления от очага", () => {
    const hot = computeHotNodeTemps(seat, chain([100, 100, 100, 100]), AMB, baseAll).hot;
    const over = (n: string) => (hot[n] ?? AMB) - AMB;
    // Каждый следующий узел холоднее предыдущего
    expect(over("N3")).toBeLessThan(over("N2"));
    expect(over("N4")).toBeLessThan(over("N3"));
    expect(over("N5")).toBeLessThan(over("N4"));
  });

  it("на расстоянии много больше зоны горения перегрев практически исчезает", () => {
    const hot = computeHotNodeTemps(seat, chain([100, 100, 100, 100]), AMB, baseAll).hot;
    const nearFire = (hot["N2"] ?? AMB) - AMB;
    const farAway  = (hot["N6"] ?? AMB) - AMB;   // ~412 м от очага
    expect(nearFire).toBeGreaterThan(20);        // у очага горячо
    expect(farAway).toBeLessThan(nearFire * 0.1); // вдали — почти фон
  });
});

// ─────────────────────────────────────────────────────────────────────────────
// Температура принадлежит СТРУЕ, а не узлу (ветвевые температуры).
//
// Сторожит ошибку, из-за которой расход при пожаре РОС вместо падения.
// Температуры хранились в узлах, и ветвь со СВЕЖИМ воздухом, впадающая в
// задымлённый узел, получала на своём конце температуру дыма. Решатель считал
// её горячим столбом и добавлял тягу, засасывающую воздух в шахту: в тесте
// решателя свежая выработка получала +73 м³/с из ниоткуда, а ветвь очага
// ложно опрокидывалась.
//
// Правильно: подогрет только тот конец ветви, по которой дым реально течёт.
// ─────────────────────────────────────────────────────────────────────────────
describe("Температуры концов ветвей", () => {
  const N = 8.52, Qfire = 35.58, Qfresh = 35.58;
  const T = calcFireTemp(N, Qfire, AMB);

  it("свежая ветвь остаётся холодной на обоих концах, даже впадая в задымлённый узел", () => {
    const { hot, branchTemps } = computeHotNodeTemps(
      seats(T, Qfire, Qfire), net(Qfire, Qfresh), AMB, base);

    // Узел сопряжения действительно нагрет — дым туда пришёл.
    expect(hot["N2"]).toBeGreaterThan(AMB + 5);

    // Но встречная СВЕЖАЯ струя (N4→N2) холодная на входе И на выходе:
    // она смешивается с дымом только ПОСЛЕ узла.
    const cold = branchTemps["C"];
    expect(cold.tFrom).toBeCloseTo(AMB, 1);
    expect(cold.tTo).toBeCloseTo(AMB, 1);
  });

  it("ветвь очага греется только на выходе (ступенька в середине выработки)", () => {
    const { branchTemps } = computeHotNodeTemps(
      seats(T, Qfire, Qfire), net(Qfire, Qfresh), AMB, base);

    const fire = branchTemps["F"];
    // До очага идёт свежий воздух, после — продукты горения.
    expect(fire.tFrom).toBeCloseTo(AMB, 1);
    expect(fire.tTo).toBeGreaterThan(AMB + 5);
  });
});
