// ─────────────────────────────────────────────────────────────────────────────
// resistanceUnits.ts — ЕДИНСТВЕННОЕ место, где живёт единица аэродинамического
// сопротивления. Всё остальное в проекте обязано ссылаться сюда.
//
// СОГЛАШЕНИЕ ПРОЕКТА (принято как единственно верное):
//
//   R хранится в Н·с²/м⁸ (СИ), и депрессия считается БЕЗ переводных множителей:
//       ΔP [Па] = R [Н·с²/м⁸] · Q² [м³/с]
//
//   В этих же паскалях выражены напор вентилятора, естественная тяга и тепловая
//   депрессия пожара, поэтому все слагаемые уравнения контура складываются
//   напрямую — ни в решателе, ни во фронте множителя g больше нет.
//
// ПОЧЕМУ ЭТО ПРИШЛОСЬ ЧИНИТЬ. Раньше в коде уживались две разные единицы.
// Формула Аткинсона R = α·P·L/S³ со справочным α (×10⁻⁴ Н·с²/м⁴) даёт результат
// СРАЗУ в Н·с²/м⁸, то есть ΔP=R·Q² уже в паскалях. Но depression() домножала
// результат ещё на 9,81, считая R рудничными кМюрг. Одновременно сопротивление
// перемычек, откалиброванное по эталонам «АэроСети», выдавалось в НАСТОЯЩИХ
// кМюрг (с делением на g) и складывалось с R выработки — то есть в одной сумме
// лежали слагаемые, отличающиеся множителем 9,81. Решатель же считал R·Q² как
// паскали, вообще без множителя. Отсюда и расхождение по ветви 432: депрессия
// выработок завышалась в 9,81 раза, вклад перемычек во столько же занижался, а
// расход после увязки не сходился ни с «Вентиляцией», ни с «АэроСетью».
//
// РУДНИЧНЫЕ ЕДИНИЦЫ НИКУДА НЕ ДЕЛИСЬ — они остаются единицей ОТОБРАЖЕНИЯ.
// Пользователь по-прежнему видит и вводит кМюрг, просто перевод выполняется
// на границе интерфейса (toDisplay/fromDisplay), а не размазан по формулам.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Ускорение свободного падения — переводной множитель между СИ и рудничными
 * единицами сопротивления.
 *
 *   1 кМюрг (кгс·с²/м⁸) = 9,80665 Н·с²/м⁸
 *
 * Значение стандартное (ГОСТ 8.417), им же откалиброваны формулы перемычек по
 * эталонам «АэроСети». Округлённое 9,81 больше нигде не используется: разница
 * в 0,03 % сама по себе безобидна, но два разных числа в одном расчёте — нет.
 */
export const G_ACCEL = 9.80665;

/** R из рудничных кМюрг (кгс·с²/м⁸) в расчётные Н·с²/м⁸. */
export function kmurgToSi(rKmurg: number): number {
  return rKmurg * G_ACCEL;
}

/** R из расчётных Н·с²/м⁸ в рудничные кМюрг (кгс·с²/м⁸) — только для показа. */
export function siToKmurg(rSi: number): number {
  return rSi / G_ACCEL;
}

/**
 * R из МЮРГ в расчётные Н·с²/м⁸ (1 кМюрг = 1000 Мюрг).
 *
 * В Мюрг хранятся поля справочника перемычек: TopoBranch.bulkheadR,
 * SchemaSymbol.bkBulkheadR, fanCrossingR. Величина мелкая, и её легко спутать
 * с кМюрг — именно так и случилось: запасная ветка расчёта перемычки брала
 * Мюрг как кМюрг и завышала сопротивление в тысячу раз.
 */
export function murgToSi(rMurg: number): number {
  return kmurgToSi(rMurg / 1000);
}

/**
 * Депрессия ветви, Па: ΔP = R·|Q|·Q.
 *
 * Знак сохраняется (R·|Q|·Q, а не R·Q²): по нему видно, течёт воздух по
 * направлению ветви или против него.
 */
export function depressionPa(rSi: number, q: number): number {
  const dp = rSi * Math.abs(q) * q;
  return Number.isFinite(dp) ? dp : 0;
}

/**
 * R из расчётных Н·с²/м⁸ в БАЗОВУЮ единицу справочника единиц (Мюрг).
 *
 * unitsConfig объявляет baseUnit = «Мюрг» (1 кМюрг = 1000 Мюрг), и все
 * fromBase() ждут именно её. Перевод короткий, но раньше он был записан
 * по-разному в разных панелях (где-то `r*1000`, где-то `r/9.81e-3`), из-за
 * чего одно и то же сопротивление показывалось в двух видах.
 */
export function siToBaseUnit(rSi: number): number {
  return siToKmurg(rSi) * 1000;
}

/**
 * Сопротивление перемычки ГВУ, установленной «внутри перемычки», Н·с²/м⁸.
 *
 * Поле fanCrossingR исторически хранится в МЮРГ (базовая единица справочников,
 * 1 кМюрг = 1000 Мюрг), поэтому перевод двойной: Мюрг → кМюрг → СИ. Раньше эти
 * две строчки были скопированы в четыре места, и в решатель уходило кМюрг,
 * а в панель — оно же, но сложенное с СИ-слагаемыми.
 */
export function fanCrossingRsi(b: {
  hasFan?: boolean;
  fanInstall?: string;
  fanCrossingR?: number;
}): number {
  const inside = b.hasFan && (b.fanInstall ?? "Внутри перемычки") === "Внутри перемычки";
  if (!inside) return 0;
  return kmurgToSi((b.fanCrossingR ?? 0) / 1000);
}

/**
 * Сопротивление по данным воздушно-депрессионной съёмки: R = ΔP/Q².
 *
 * ΔP замеряется в паскалях, значит R получается сразу в Н·с²/м⁸ — деления на g
 * здесь быть не должно (раньше оно стояло и занижало R съёмки в 9,81 раза).
 */
export function resistanceFromSurvey(dpPa: number, q: number): number {
  if (!(q > 0)) return 0;
  const r = dpPa / (q * q);
  return Number.isFinite(r) ? r : 0;
}