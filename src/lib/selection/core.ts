// ─────────────────────────────────────────────────────────────────────────────
// core.ts — единое ядро подбора оборудования по характеристике Q–H.
//
// ЗАЧЕМ. Подбор вентиляторов (lib/fans.ts) и насосов (lib/pumps.ts) считался
// двумя почти дословными копиями одного алгоритма: аппроксимация кривой
// H(Q) = H0 + a·Q + b·Q², парабола КПД вокруг Qopt, поиск рабочей точки
// делением отрезка пополам, скоринг и предупреждения. Любая правка формулы
// требовала синхронной правки в двух местах — и рано или поздно они разъехались
// бы (у насосов, например, функции подбора selectPumps не было вовсе).
//
// Здесь общая часть собрана один раз и параметризована видом оборудования.
// Физическая разница между вентилятором и насосом выражается ровно двумя
// величинами:
//   • единицы напора: у вентилятора Па, у насоса метры водяного столба;
//   • статический напор Hst: у насоса это геометрическая высота подъёма,
//     которую нужно преодолеть даже при нулевой подаче; у вентилятора его нет.
// Всё остальное совпадает.
//
// ВАЖНО: формулы, коэффициенты и пороги перенесены БЕЗ изменений — подбор
// обязан давать ровно те же числа, что и раньше.
// ─────────────────────────────────────────────────────────────────────────────

/** Плотность воды, кг/м³ — для мощности насоса. */
const WATER_DENSITY = 1000;
/** Ускорение свободного падения, м/с². */
const G = 9.81;

/**
 * Аппроксимация характеристики оборудования: H(Q) = H0 + a·Q + b·Q².
 * Общая часть моделей вентилятора и насоса.
 */
export interface CurveModel {
  /** Напор при нулевой подаче (Па для вентилятора, м для насоса). */
  H0: number;
  /** Коэффициент при Q. */
  a: number;
  /** Коэффициент при Q². */
  b: number;
  /** Нижняя граница рабочего диапазона, м³/ч. */
  Qmin: number;
  /** Верхняя граница рабочего диапазона, м³/ч. */
  Qmax: number;
  /** Подача в оптимальной точке, м³/ч. */
  Qopt: number;
  /** КПД в оптимальной точке, 0..1. */
  etaMax: number;
  /** Мощность двигателя, кВт — запасной вариант, когда КПД неприменим. */
  power: number;
}

/** Вид оборудования — задаёт единицы напора и способ расчёта мощности. */
export type EquipmentKind = "fan" | "pump";

/**
 * Исполнение корпуса и двигателя — где машину вообще разрешено ставить.
 *
 * Для шахты это не характеристика «на будущее», а допуск: в выработке,
 * опасной по газу или пыли, общепромышленный двигатель ставить нельзя,
 * сколь угодно удачной ни была бы его рабочая точка. Поэтому исполнение
 * проверяется до скоринга — как фильтр, а не как штраф.
 */
export type Execution =
  | "general"              // общепромышленное
  | "explosion_proof"      // взрывозащищённое (РВ, рудничное)
  | "corrosion_resistant"  // коррозионностойкое (шахтные воды, кислая среда)
  | "heat_resistant";      // жаростойкое (дымоудаление)

/** Подписи исполнений для интерфейса. */
export const EXECUTION_LABELS: Record<Execution, string> = {
  general: "Общепромышленное",
  explosion_proof: "Взрывозащищённое",
  corrosion_resistant: "Коррозионностойкое",
  heat_resistant: "Жаростойкое",
};

/**
 * Дополнительные свойства модели, влияющие на подбор, но не на кривую H(Q).
 *
 * Вынесены в ядро, потому что нужны и вентиляторам, и насосам: поле
 * заполняется в каталоге, а учитывается в общей логике отбора и оценки.
 */
export interface EquipmentOptions {
  /**
   * Допускает частотное регулирование (ЧРП/ПЧ).
   *
   * Меняет смысл избыточной подачи: у машины с частотником избыток не брак,
   * а запас — обороты снижают, и точка садится на требуемую. У машины без
   * частотника избыток приходится душить задвижкой или шибером, то есть
   * греть сеть впустую.
   */
  vfd?: boolean;
  /** Исполнение; не задано — считается общепромышленным. */
  execution?: Execution;
  /** Число ступеней (рабочих колёс) — у секционных насосов. */
  stages?: number;
}

/** Модель каталога: кривая плюс свойства, влияющие на отбор. */
export type SelectableModel = CurveModel & EquipmentOptions;

/** Исполнение модели с учётом умолчания. */
export function executionOf(m: EquipmentOptions): Execution {
  return m.execution ?? "general";
}

/**
 * Модель допустима в заданных условиях.
 *
 * Взрывозащищённое исполнение перекрывает общепромышленное требование, но
 * не наоборот: поставить РВ-машину там, где хватило бы обычной, можно —
 * обратное запрещено правилами безопасности.
 */
export function executionAllowed(m: EquipmentOptions, required?: Execution): boolean {
  if (!required || required === "general") return true;
  return executionOf(m) === required;
}

// ─── Частотное регулирование ─────────────────────────────────────────────────

/**
 * Во сколько раз снизить обороты, чтобы рабочая точка села на требуемую подачу.
 *
 * Законы подобия: Q ~ n, H ~ n², P ~ n³. Значит отношение оборотов равно
 * отношению подач. Возвращает 1, когда снижать нечего (подачи и так не хватает).
 */
export function vfdSpeedRatio(pointQ: number, requiredQ: number): number {
  if (pointQ <= 0 || requiredQ <= 0) return 1;
  return Math.min(1, requiredQ / pointQ);
}

/**
 * Мощность после снижения оборотов частотником, кВт.
 *
 * P ~ n³ — отсюда и весь смысл частотника: избыток подачи в 20% снимается
 * почти вдвое меньшей мощностью (0.8³ ≈ 0.51), тогда как дросселирование
 * задвижкой не экономит почти ничего.
 */
export function vfdPower(power: number, speedRatio: number): number {
  return power * speedRatio * speedRatio * speedRatio;
}

/** Рабочая точка — пересечение характеристики оборудования и кривой сети. */
export interface OperatingPointBase {
  /** Подача в рабочей точке, м³/ч. */
  Q: number;
  /** Напор в рабочей точке (Па для вентилятора, м для насоса). */
  H: number;
  /** КПД в рабочей точке, 0..1. */
  eta: number;
  /** Мощность на валу, кВт. */
  power: number;
  /** Рабочая точка попадает в допустимый диапазон оборудования. */
  found: boolean;
  /** Точка близка к оптимуму (отклонение от Qopt менее 25%). */
  inOptimalZone: boolean;
  /** Запас по подаче относительно требуемой, %. */
  marginQ: number;
  /** Запас по напору относительно требуемого, %. */
  marginH: number;
}

// ─── Характеристика ──────────────────────────────────────────────────────────

/**
 * Напор оборудования при подаче Q.
 * Отрицательные значения отсекаются: за пределами кривой напора нет.
 */
export function curveHead(m: CurveModel, Q: number): number {
  return Math.max(0, m.H0 + m.a * Q + m.b * Q * Q);
}

/**
 * КПД при подаче Q — парабола вокруг оптимальной точки.
 *
 * Упрощение: паспортная кривая КПД заменена параболой η(Q) = ηmax·(1 − 0.6·r²),
 * где r — относительное отклонение от Qopt. Нижняя граница 0.1·ηmax не даёт
 * КПД обнулиться на краях диапазона, иначе мощность ушла бы в бесконечность.
 */
export function curveEfficiency(m: CurveModel, Q: number): number {
  if (Q <= 0 || Q > m.Qmax * 1.1) return 0;
  const ratio = (Q - m.Qopt) / m.Qopt;
  const eta = m.etaMax * Math.max(0.1, 1 - 0.6 * ratio * ratio);
  return Math.min(m.etaMax, eta);
}

/**
 * Мощность на валу при подаче Q, кВт.
 *
 * Вентилятор: P = Q·H / (3600·η·1000), где H в Па.
 * Насос:      P = ρ·g·Q·H / (3600·η·1000), где H в метрах.
 *
 * При КПД ниже 5% формула неприменима (деление на почти ноль даёт абсурдные
 * величины), поэтому возвращается паспортная мощность двигателя.
 */
export function curvePower(m: CurveModel, Q: number, kind: EquipmentKind): number {
  const H = curveHead(m, Q);
  const eta = curveEfficiency(m, Q);
  if (eta < 0.05) return m.power;
  const numerator = kind === "pump" ? WATER_DENSITY * G * Q * H : Q * H;
  return numerator / (3600 * eta * 1000);
}

// ─── Рабочая точка ───────────────────────────────────────────────────────────

export interface OperatingPointOptions {
  /** Приведённое сопротивление сети S в H = Hst + S·Q². */
  networkS: number;
  /** Требуемая подача, м³/ч — от неё считается запас. */
  requiredQ: number;
  /** Требуемый напор — от него считается запас. */
  requiredH: number;
  /**
   * Статический напор Hst (только насосы): геометрическая высота подъёма.
   * У вентилятора равен нулю — воздух не поднимают на высоту против тяжести.
   */
  staticHead?: number;
  /** Округление напора: вентилятор до целых Па, насос до десятых метра. */
  headDecimals?: number;
  /** Округление мощности: вентилятор до тысячных кВт, насос до сотых. */
  powerDecimals?: number;
}

/**
 * Рабочая точка — пересечение кривой оборудования H(Q) и кривой сети
 * Hst + S·Q².
 *
 * Решается делением отрезка пополам по Q. Обе кривые монотонны в рабочей
 * области (напор оборудования падает с ростом подачи, сопротивление сети
 * растёт), поэтому пересечение единственное и метод всегда сходится.
 * 60 итераций дают точность заведомо выше инженерной.
 */
export function findOperatingPoint(
  m: CurveModel,
  kind: EquipmentKind,
  opts: OperatingPointOptions,
): OperatingPointBase {
  const {
    networkS, requiredQ, requiredH,
    staticHead = 0,
    headDecimals = 0,
    powerDecimals = 3,
  } = opts;

  let lo = 0;
  let hi = m.Qmax * 1.2;
  for (let i = 0; i < 60; i++) {
    const mid = (lo + hi) / 2;
    const Hequip = curveHead(m, mid);
    const Hnet = staticHead + networkS * mid * mid;
    if (Hequip > Hnet) lo = mid; else hi = mid;
  }

  const Q = (lo + hi) / 2;
  const H = curveHead(m, Q);
  const eta = curveEfficiency(m, Q);
  const power = curvePower(m, Q, kind);

  // Рабочая точка засчитывается с допуском по краям диапазона: 70% от Qmin
  // и 105% от Qmax. Оборудование на границе работоспособно, но будет отмечено
  // предупреждением при скоринге.
  const found = Q >= m.Qmin * 0.7 && Q <= m.Qmax * 1.05 && H > 0;
  const inOptimalZone = Math.abs(Q - m.Qopt) / m.Qopt < 0.25;

  // Защита от деления на ноль: при нулевом требовании запас не определён.
  const marginQ = requiredQ > 0 ? ((Q - requiredQ) / requiredQ) * 100 : 0;
  const marginH = requiredH > 0 ? ((H - requiredH) / requiredH) * 100 : 0;

  const headFactor = Math.pow(10, headDecimals);
  const powerFactor = Math.pow(10, powerDecimals);

  return {
    Q: Math.round(Q),
    H: Math.round(H * headFactor) / headFactor,
    eta: Math.round(eta * 100) / 100,
    power: Math.round(power * powerFactor) / powerFactor,
    found,
    inOptimalZone,
    marginQ: Math.round(marginQ),
    marginH: Math.round(marginH),
  };
}

// ─── Скоринг ─────────────────────────────────────────────────────────────────

/** Оценка пригодности оборудования и замечания к нему. */
export interface ScoreResult {
  /** Оценка 0..100, чем выше — тем лучше подходит. */
  score: number;
  /** Замечания для показа рядом с моделью. */
  warnings: string[];
}

/**
 * Оценка пригодности оборудования в рабочей точке.
 *
 * Шкала (перенесена из прежнего подбора вентиляторов без изменений):
 *   60  — база, если рабочая точка вообще найдена;
 *   +20 — работа вблизи оптимума;
 *   +10 — разумный запас по подаче (5…30%);
 *   −30 — подача НИЖЕ требуемой (оборудование не справится);
 *   −20 — избыточный запас свыше 50% (переразмеренное оборудование);
 *   +25·η — вклад КПД (при η = 0.7 это +17.5).
 *
 * Почему дефицит подачи штрафуется сильнее избытка: переразмеренный насос или
 * вентилятор работает неэкономично, но задачу решает, а недостаточный —
 * не решает вовсе.
 */
export function scoreOperatingPoint(
  m: SelectableModel,
  point: OperatingPointBase,
  unitLabel: string,
): ScoreResult {
  const warnings: string[] = [];

  if (!point.found) {
    warnings.push("Рабочая точка вне диапазона");
    return { score: 0, warnings };
  }

  let score = 60;
  if (point.inOptimalZone) score += 20;

  if (point.marginQ >= 5 && point.marginQ <= 30) {
    score += 10;
  } else if (point.marginQ < 0) {
    score -= 30;
    warnings.push(`${unitLabel} ниже требуемого на ${Math.abs(point.marginQ)}%`);
  } else if (point.marginQ > 50) {
    // Избыток подачи: с частотником он снимается снижением оборотов, и штраф
    // втрое меньше. Без частотника избыток душат задвижкой — энергия уходит
    // в потери, поэтому прежние −20 остаются.
    if (m.vfd) {
      score -= 7;
      warnings.push(
        `Избыток ${unitLabel.toLowerCase()}а +${point.marginQ}% — снимается частотником`,
      );
    } else {
      score -= 20;
      warnings.push(`Большой избыток ${unitLabel.toLowerCase()}а (+${point.marginQ}%)`);
    }
  }

  score += point.eta * 25;

  if (point.eta < m.etaMax * 0.8) {
    warnings.push(
      `КПД ниже оптимума (${Math.round(point.eta * 100)}% vs ${Math.round(m.etaMax * 100)}%)`,
    );
  }

  return {
    score: Math.max(0, Math.min(100, Math.round(score))),
    warnings,
  };
}

// ─── Сопротивление сети ──────────────────────────────────────────────────────

/**
 * Приведённое сопротивление сети из требуемой пары Q–H: S = (H − Hst) / Q².
 *
 * Именно эта величина задаёт кривую сети, по которой ищется рабочая точка.
 * При нулевой или отрицательной подаче возвращается 0 — кривая вырождается,
 * и подбор в таком случае бессмысленен.
 */
export function networkResistance(
  requiredQ: number,
  requiredH: number,
  staticHead = 0,
): number {
  if (requiredQ <= 0) return 0;
  return Math.max(0, requiredH - staticHead) / (requiredQ * requiredQ);
}