/**
 * Из чего складывается стрелка: наконечник и хвостик.
 *
 * Пропорции взяты с чертежа (canvasRenderer: наконечник 2.2 ширины линии,
 * хвостик 3.0, толщина хвостика 0.15 от полуширины наконечника). Два режима
 * обязаны показывать одну и ту же стрелку: человек, привыкший читать
 * направление на чертеже, не должен заново привыкать к объёму.
 */
const HEAD_FRAC = 2.2 / 5.2;        // доля длины, приходящаяся на наконечник
const TAIL_R_FRAC = 0.15;           // толщина хвостика от радиуса наконечника
/** Во сколько раз стрелка целиком длиннее своей толщины. */
const ARROW_LEN_K = 5.2;

/**
 * Единичная стрелка остриём вдоль +X: наконечник плюс хвостик.
 *
 * Длина всей стрелки — ровно 1, чтобы матрица экземпляра растягивала её по
 * длине выработки одним числом, а шейдер сдвигал по локальному X.
 *
 * ConeGeometry и CylinderGeometry в three смотрят вдоль оси Y, поэтому сразу
 * разворачиваем их: дальше матрица экземпляра работает так же, как у
 * выработок, — переводит +X в направление потока.
 *
 * Донышки (openEnded = false) оставляем: без них сквозь стрелку видно её
 * внутренность, и на светлой схеме она выглядит дырой.
 */
function makeArrowGeometry(): THREE.BufferGeometry {
  const headLen = HEAD_FRAC;
  const tailLen = 1 - headLen;

  const head = new THREE.ConeGeometry(1, headLen, CONE_FACETS, 1, false);
  // Остриё ConeGeometry в +Y, центр в середине высоты. Сдвигаем так, чтобы
  // основание наконечника пришлось на конец хвостика, а остриё — точно в 1.
  head.translate(0, 1 - headLen / 2, 0);
  head.rotateZ(-Math.PI / 2);

  // Хвостик заходит под наконечник на четверть его длины: иначе на стыке при
  // косом взгляде видна щель между тонкой трубкой и широким основанием.
  const stemLen = tailLen + headLen * 0.25;
  const tail = new THREE.CylinderGeometry(
    TAIL_R_FRAC, TAIL_R_FRAC, stemLen, Math.max(6, CONE_FACETS / 2), 1, false,
  );
  tail.translate(0, stemLen / 2, 0);
  tail.rotateZ(-Math.PI / 2);

  const merged = mergeGeometries([head, tail], false);
  head.dispose();
  tail.dispose();
  // mergeGeometries возвращает null, если наборы атрибутов разошлись. У обеих
  // заготовок они одинаковые, но подстраховаться дешевле, чем уронить режим:
  // без стрелок схема читается, с пустым экраном — нет.
  if (!merged) {
    const fallback = new THREE.ConeGeometry(1, 1, CONE_FACETS, 1, false);
    fallback.translate(0, 0.5, 0);
    fallback.rotateZ(-Math.PI / 2);
    return fallback;
  }
  return merged;
}

/**
 * Поперечный размер выработки, м — по нему подбирается размер стрелки.
 *
 * Берём ПОЛОВИНУ ДИАГОНАЛИ сечения, а не половину большей стороны: у
 * прямоугольного сечения угол отстоит от оси дальше, чем середина стенки, и
 * при повороте схемы наружу выходит именно он. Считай по стенке — стрелка,
 * отведённая на эту величину, временами пряталась бы за углом выработки.
 */
function sectionRadius(b: TopoBranch): number {
  if ((b.shape ?? "rect") === "round") return Math.max(0.5, (b.diameter ?? 0) / 2);
  const w = Math.max(0.5, b.rectWidth ?? 0);
  const h = Math.max(0.5, b.rectHeight ?? 0) + Math.max(0, b.archHeight ?? 0);
  return Math.hypot(w, h) / 2;
}

/**
 * ВПИСАННЫЙ радиус сечения, м — расстояние от оси до ближайшей стенки.
 *
 * Нужен, когда стрелка идёт ВНУТРИ выработки: по нему подбирается её толщина
 * так, чтобы она нигде не проткнула стенку. Полудиагональ (sectionRadius выше)
 * здесь не годится — она, наоборот, до самого дальнего угла, и стрелка такого
 * размера вылезла бы из выработки боками.
 *
 * Считаем честно по контуру: расстояние от центра до каждого его ребра, берём
 * наименьшее. Для прямоугольника это половина меньшей стороны, для свода —
 * расстояние до стенки или до пяты свода, смотря что ближе.
 */
function inscribedRadius(b: TopoBranch): number {
  const outline = sectionOutline(b);
  const n = outline.length;
  if (n < 3) return 0.5;

  let min = Infinity;
  for (let i = 0; i < n; i++) {
    const p0 = outline[i];
    const p1 = outline[(i + 1) % n];
    const er = p1.r - p0.r, eu = p1.u - p0.u;
    const el = Math.hypot(er, eu);
    if (!(el > 1e-9)) continue;
    // Расстояние от начала координат (центра сечения) до прямой ребра.
    const d = Math.abs(er * p0.u - eu * p0.r) / el;
    if (d < min) min = d;
  }
  return isFinite(min) && min > 0.05 ? min : 0.5;
}

/**
 * Куда отодвинуть стрелку от оси выработки.
 *
 * Ищем нормаль к выработке, максимально близкую к «вверх»: у горизонтальной
 * выработки стрелка идёт над кровлей — там её не закрывает ни сама выработка,
 * ни соседние, лежащие в том же горизонте. У вертикального ствола «вверх»
 * совпадает с осью и нормали не даёт; там берём горизонтальное направление —
 * стрелка идёт рядом со стволом сбоку.
 *
 * В координатах сцены вверх — ось Y (см. toThree).
 */
function offsetNormal(dir: THREE.Vector3): THREE.Vector3 {
  const up = new THREE.Vector3(0, 1, 0);
  // Составляющая «вверх», перпендикулярная выработке.
  const n = up.clone().sub(dir.clone().multiplyScalar(dir.dot(up)));
  if (n.lengthSq() > 1e-6) return n.normalize();
  // Выработка вертикальна — вверх не годится, отводим стрелку по оси X сцены.
  const side = new THREE.Vector3(1, 0, 0);
  const n2 = side.clone().sub(dir.clone().multiplyScalar(dir.dot(side)));
  if (n2.lengthSq() > 1e-6) return n2.normalize();
  return new THREE.Vector3(0, 0, 1);
}

/** Геометрия одной выработки, посчитанная до раскладки стрелок. */
interface Placement {
  branch: TopoBranch;
  from: THREE.Vector3;
  dir: THREE.Vector3;
  /** Длина выработки в координатах сцены. */
  len: number;
  /** Радиус наконечника и полная длина стрелки (хвостик + наконечник). */
  rad: number;
  aLen: number;
  /**
   * Смещение стрелки от оси выработки, координаты сцены.
   *
   * Уже готовый вектор: нормаль, умноженная на величину отвода. Складывается с
   * начальной точкой — так стрелка идёт ВДОЛЬ выработки, но снаружи неё.
   */
  offset: THREE.Vector3;
  /** Отступ от узлов: на него стрелка отодвинута от начала выработки. */
  margin: number;
  /** Сколько стрелок ставим и с каким шагом. */
  count: number;
  step: number;
  /**
   * Стрелка бежит, а не стоит.
   *
   * На выработке короче одного шага потока цикл пришлось бы укоротить до её
   * длины — а короткий цикл означает частые перескоки «конец → начало», то
   * самое мельтешение. Там стрелку останавливаем: направление она показывает
   * и неподвижной, а на двухметровой сбойке движение маркера всё равно не
   * читается.
   */
  moving: boolean;
  /** Скорость бега в координатах сцены, единиц в секунду. */
  speed: number;
}

/**
 * Считает раскладку стрелок по выработкам.
 *
 * Вынесено отдельно, потому что число экземпляров в пакетной отрисовке
 * задаётся заранее и потом не меняется: сначала надо узнать, сколько всего
 * стрелок получится, и только потом создавать меш.
 */
function planArrows(input: ArrowsInput): { plan: Placement[]; total: number } {
  const { nodes, branches, xyScale, zScale } = input;
  const nodeById = new Map(nodes.map(n => [n.id, n]));
  const kx = xyScale > 0 ? xyScale : 1;
  const kz = zScale > 0 ? zScale : 1;
  const animK = Math.max(0.1, input.animSpeed ?? 1);
  const inside = input.inside === true;

  const plan: Placement[] = [];
  let total = 0;

  // ── ЕДИНЫЙ ШАГ ПОТОКА НА ВСЮ СХЕМУ ───────────────────────────────────
  //
  // Считаем его ОДИН раз, до раскладки, по СРЕДНЕМУ сечению рассчитанных
  // выработок. Средним, а не по каждой выработке своим: шаг обязан быть общим,
  // иначе цикл у каждой окажется своей длины и синхронность потеряется (см.
  // FLOW_PITCH_K). Медиану не берём — на схеме в тысячи выработок сортировка
  // дороже самой раскладки, а разницы на глаз нет.
  let secSum = 0, secCnt = 0;
  for (const b of branches) {
    if (b.isDead) continue;
    if (Math.abs(b.flow ?? 0) < MIN_FLOW) continue;
    secSum += inside ? inscribedRadius(b) : sectionRadius(b);
    secCnt++;
  }
  if (secCnt === 0) return { plan, total: 0 };
  const secAvg = (secSum / secCnt) * kx;
  // Длина стрелки того же размера, что и в раскладке ниже, но от СРЕДНЕГО
  // сечения — она и задаёт шаг, одинаковый для всей схемы.
  const aLenAvg = secAvg * (inside ? 0.55 : 0.65) * (inside ? ARROW_LEN_K * 1.8 : ARROW_LEN_K);
  const pitch = Math.max(1e-6, aLenAvg * FLOW_PITCH_K);

  for (const b of branches) {
    if (b.isDead) continue;
    if (Math.abs(b.flow ?? 0) < MIN_FLOW) continue;
    const fn = nodeById.get(b.fromId), tn = nodeById.get(b.toId);
    if (!fn || !tn) continue;
    if (!isFinite(fn.x) || !isFinite(fn.y) || !isFinite(fn.z)) continue;
    if (!isFinite(tn.x) || !isFinite(tn.y) || !isFinite(tn.z)) continue;

    // Направление стрелки — по воздуху, а не по тому, как выработку начертили.
    // Отрицательный расход означает движение против направления выработки; у
    // вентилятора в реверсе знак может не смениться, поэтому он учитывается
    // отдельно — ровно так же, как на чертеже.
    const fanReverseOverride = b.hasFan && (b.fanReverse ?? false) && (b.flow ?? 0) >= 0;
    const reversed = (b.flow ?? 0) < 0 || fanReverseOverride;
    const a = reversed ? tn : fn;
    const c = reversed ? fn : tn;

    const from = toThree(a.x * kx, a.y * kx, a.z * kz);
    const to = toThree(c.x * kx, c.y * kx, c.z * kz);
    const dir = new THREE.Vector3().subVectors(to, from);
    const len = dir.length();
    if (!(len > 1e-6)) continue;
    dir.divideScalar(len);

    // ── Размер стрелки и её положение относительно выработки ──────────
    //
    // Сечение в сцене масштабируется тем же множителем плана, что и выработки
    // (см. branchMatrix в mineScene), поэтому размеры сечения здесь умножаются
    // на этот же множитель.
    const secR = sectionRadius(b) * kx;          // до дальнего угла
    const inR = inscribedRadius(b) * kx;         // до ближайшей стенки

    let rad: number;
    let offset: THREE.Vector3;
    let margin: number;

    if (inside) {
      // СТРЕЛКА ВНУТРИ ВЫРАБОТКИ, ПО ЕЁ ОСИ.
      //
      // Толщину берём от ВПИСАННОГО радиуса — расстояния до ближайшей стенки,
      // а не до дальнего угла. Доля 0.55 оставляет зазор со всех сторон даже у
      // вытянутого прямоугольного сечения, где запас по узкой стороне самый
      // маленький: стрелка нигде не протыкает стенку и не касается её.
      rad = inR * 0.55;
      // Смещения нет: ось стрелки совпадает с осью выработки — воздух идёт
      // ровно там, где ему и положено.
      offset = new THREE.Vector3(0, 0, 0);
      // Отступ от узлов побольше: внутри выработки стрелка не должна въезжать
      // в зону сопряжения, где сходятся несколько тел и картинка мутнеет.
      margin = Math.min(secR * 1.2, len * 0.15);
    } else {
      // СТРЕЛКА СНАРУЖИ (сплошной режим).
      //
      // Наконечник соразмерен выработке, но заметно тоньше её: стрелка должна
      // читаться как указатель направления, а не спорить с самой выработкой за
      // место на экране.
      rad = secR * 0.65;
      // Отвод от оси: радиус выработки плюс весь радиус стрелки плюс небольшой
      // зазор. Меньше — стрелка врезается в трубу и её снова начинает
      // перекрывать поверхность выработки.
      offset = offsetNormal(dir).multiplyScalar(secR + rad + secR * 0.08);
      // В узле сходится несколько выработок, и там они врезаются друг в друга.
      // Стрелка, доходящая вплотную до узла, попадает в этот стык и выглядит
      // приклеенной к соседней выработке.
      margin = Math.min(secR, len * 0.12);
    }
    if (!(rad > 1e-6)) continue;

    // Длина стрелки соразмерна её толщине, но не длиннее части свободного
    // участка: на короткой сбойке стрелка иначе заняла бы её целиком.
    //
    // Внутри выработки стрелку удлиняем: её толщина зажата ближайшей стенкой и
    // при обычной пропорции стрелка выходила бы куцым огрызком. Вытянутая же
    // читается как указатель направления и на узком сечении.
    const free = len - margin * 2;
    if (!(free > 1e-6)) continue;
    const lenK = inside ? ARROW_LEN_K * 1.8 : ARROW_LEN_K;
    const aLen = Math.min(rad * lenK, free * 0.6);
    if (!(aLen > 1e-6)) continue;

    // ── Шаг и число стрелок ───────────────────────────────────────────
    //
    // Шаг — ОБЩИЙ на всю схему (pitch), а не «полторы длины этой стрелки».
    // Раньше он считался от длины конкретной стрелки, и вместе с ним у каждой
    // выработки получался свой цикл: на сбойке стрелка пробегала его за
    // мгновение и дёргалась, на штреке ползла. Теперь цикл один и тот же
    // везде, и поток идёт в лад.
    //
    // Число стрелок — сколько целых шагов укладывается в свободную часть.
    // Ноль недопустим: выработка с расходом обязана показывать направление,
    // даже если короче шага, — там ставим одну стрелку.
    //
    // Округление ВНИЗ, а не к ближайшему: при округлении вверх на выработке
    // чуть длиннее полутора шагов появлялись две стрелки, и цепочка сжималась
    // — соседние выработки с той же длиной показывали разную плотность.
    const step = pitch;
    const fit = Math.floor(free / step);
    const count = Math.max(1, Math.min(MAX_PER_BRANCH, fit));

    // ── ДВИГАТЬ ЛИ СТРЕЛКУ ────────────────────────────────────────────
    //
    // Двигаем только там, где в выработку укладывается хотя бы один ПОЛНЫЙ
    // шаг. Иначе цикл пришлось бы укоротить до длины выработки, а короткий
    // цикл — это и есть «триггер»: стрелка успевает добежать до конца и
    // прыгнуть в начало по нескольку раз в секунду.
    //
    // Расчёт же требует показать направление в КАЖДОЙ выработке с расходом,
    // включая двухметровые сбойки. Поэтому там стрелка остаётся, но стоит:
    // куда идёт воздух, видно и по неподвижной, а мельтешения больше нет.
    const moving = fit >= 1;

    if (total + count > MAX_TOTAL) break;

    // Скорость бега — по общему закону (flowAnim), одному на чертёж и на
    // модель: метры рудника в секунду, приведённые к масштабу плана.
    const speed = arrowSpeedMps(b.velocity, animK) * kx;

    plan.push({ branch: b, from, dir, len, rad, aLen, offset, margin, count, step, moving, speed });
    total += count;
  }

  return { plan, total };
}

/**
 * Строит бегущие стрелки потока.
 *
 * Возвращает null, если ставить нечего: схема не рассчитана или воздух никуда
 * не идёт. Вызывающая сторона в этом случае просто ничего не добавляет в сцену.
 */
export function buildFlowArrows(input: ArrowsInput): FlowArrows | null {
  const { plan, total } = planArrows(input);
  if (total === 0) return null;

  const geom = makeArrowGeometry();

  // ── Данные для шейдера, по одному числу на стрелку ────────────────────
  // Всё в ЛОКАЛЬНЫХ единицах стрелки: матрица экземпляра уже растягивает её по
  // длине выработки, поэтому смещение вдоль локальной оси X автоматически
  // превращается в движение вдоль выработки в нужную сторону. Это избавляет от
  // хранения направления отдельным вектором.
  const aSpan = new Float32Array(total);   // длина пробега
  const aSpeed = new Float32Array(total);  // единиц в секунду
  const aPhase = new Float32Array(total);  // начальный сдвиг

  const inside = input.inside === true;

  const mat = new THREE.MeshLambertMaterial({
    // Стрелка надета на выработку, и изнутри её стенка тоже попадает в кадр —
    // без DoubleSide стрелка при взгляде «в хвост» выглядит рассечённой.
    side: THREE.DoubleSide,
  });

  // Ссылку на переменную времени держим снаружи: она появляется только в
  // момент компиляции шейдера, а двигать стрелки нужно каждый кадр.
  const timeUniform = { value: 0 };

  mat.onBeforeCompile = (shader) => {
    shader.uniforms.uTime = timeUniform;
    shader.vertexShader = shader.vertexShader
      .replace(
        "#include <common>",
        `#include <common>
         attribute float aSpan;
         attribute float aSpeed;
         attribute float aPhase;
         uniform float uTime;`,
      )
      // Вмешиваемся ДО project_vertex: там вершина ещё в локальных координатах
      // стрелки и матрица экземпляра к ней не применена. Сдвиг по локальному X
      // как раз и станет движением вдоль выработки.
      .replace(
        "#include <project_vertex>",
        `transformed.x += mod(uTime * aSpeed + aPhase, aSpan);
         #include <project_vertex>`,
      );

    // Стрелка ВНУТРИ выработки светится собственным цветом, а не только
    // отражённым светом. Над ней лежит полупрозрачное тело выработки, которое
    // приглушает всё, что под ним: без подсветки стрелка внутри выглядела бы
    // блёклой тенью вместо чёткого указателя направления.
    //
    // Через поле emissive материала этого не сделать: оно одно на весь пакет,
    // а цвет струи у каждой выработки свой (красный или синий) и задаётся на
    // экземпляр. Поэтому свечение берём прямо из цвета пикселя.
    if (inside) {
      shader.fragmentShader = shader.fragmentShader.replace(
        "#include <emissivemap_fragment>",
        `#include <emissivemap_fragment>
         totalEmissiveRadiance += diffuseColor.rgb * 0.55;`,
      );
    }
  };

  const mesh = new THREE.InstancedMesh(geom, mat, total);
  mesh.instanceMatrix.setUsage(THREE.StaticDrawUsage);
  // Выработки тянутся через всю сцену, отсечение по габаритам здесь только
  // мешает: стрелка привязана к выработке, а не к точке.
  mesh.frustumCulled = false;
  // Порядок отрисовки.
  //
  // Стрелка СНАРУЖИ идёт после выработок: при равной глубине (стрелка вплотную
  // к трубе) побеждает нарисованное позже, иначе стрелка местами тонула бы в
  // поверхности выработки.
  //
  // Стрелка ВНУТРИ — наоборот, до них (renderOrder 0 против 1 у прозрачного
  // тела). Прозрачное тело смешивается с тем, что уже лежит в кадре, поэтому
  // стрелка должна быть нарисована РАНЬШЕ — тогда сквозь стенку виден её цвет.
  // Нарисуй позже — она легла бы поверх выработки и выглядела бы не внутри, а
  // на ней, и весь смысл «воздух идёт по выработке» пропал бы.
  mesh.renderOrder = inside ? 0 : 5;

  const axisX = new THREE.Vector3(1, 0, 0);
  const q = new THREE.Quaternion();
  const base = new THREE.Vector3();
  const scale = new THREE.Vector3();
  const m = new THREE.Matrix4();
  const col = new THREE.Color();
  const polluted = input.pollutedBranchIds;

  let idx = 0;
  for (const pl of plan) {
    q.setFromUnitVectors(axisX, pl.dir);
    scale.set(pl.aLen, pl.rad, pl.rad);
    // Все стрелки выработки стартуют от одной точки — на отступ от начального
    // узла; расходятся они за счёт начального сдвига в шейдере, а не за счёт
    // разных матриц. Плюс вынос по нормали: стрелка идёт вдоль выработки, но
    // снаружи её поверхности, иначе труба перекрывает стрелку целиком.
    base.copy(pl.dir).multiplyScalar(pl.margin).add(pl.from).add(pl.offset);
    m.compose(base, q, scale);

    // ── Пробег (длина цикла) ─────────────────────────────────────────
    //
    // ЗДЕСЬ И БЫЛ «ТРИГГЕР». Цикл — это путь, который стрелка проходит, прежде
    // чем перескочить обратно в начало. Чем он короче, тем чаще перескок, и
    // именно частые перескоки читаются как дёрганье.
    //
    // Раньше цикл равнялся длине выработки: на штреке — плавный ход, на
    // сбойке в пару метров — несколько перескоков в секунду. Разная длина
    // цикла = разная частота = рассогласованное мельтешение.
    //
    // Теперь цикл равен ШАГУ между стрелками, одному на всю схему. Стрелка
    // доходит ровно до места, где стоит следующая, и подменяется ею — глаз
    // перескока не замечает вовсе, цепочка выглядит непрерывной. Частота
    // одинакова везде и от длины выработки больше не зависит.
    // Перевод в локальные единицы стрелки: матрица растянула её в aLen раз.
    const spanLocal = pl.step / pl.aLen;
    // Выработка короче шага — движение выключено (см. moving в planArrows):
    // там цикл не укладывается, и любое движение свелось бы к дрожанию.
    const speedLocal = pl.moving ? pl.speed / pl.aLen : 0;

    col.set(polluted?.has(pl.branch.id) ? COLOR_POLLUTED : COLOR_FRESH);

    // Куда ставить стрелки по длине выработки.
    //
    // Раньше цепочку растягивали на весь цикл (spanLocal), а сам цикл не
    // совпадал с реальным расстоянием между стрелками — отсюда и просветы, и
    // наложения. Теперь всё просто: соседние стрелки стоят ровно на шаг друг
    // от друга, то есть на длину цикла, и подмена происходит незаметно.
    //
    // Центрировать цепочку НЕЛЬЗЯ, хотя и хочется: движущаяся стрелка всё
    // равно идёт по кругу длиной в шаг, и её положение задаётся остатком от
    // деления. Любой общий сдвиг «для красоты» этот остаток меняет и рвёт
    // привязку к мировой сетке — соседние выработки снова разъезжаются.
    // Поэтому цепочка начинается от края свободной части, а ровное покрытие
    // обеспечивает сам шаг: стрелки идут одна за другой до конца выработки.


    for (let i = 0; i < pl.count; i++) {
      mesh.setMatrixAt(idx, m);
      mesh.setColorAt(idx, col);
      // Длина цикла. У НЕПОДВИЖНОЙ стрелки цикла нет: шейдер всё равно берёт
      // остаток по этому числу, и если оно меньше отступа от края, стрелку
      // отбросило бы к началу выработки. Ставим заведомо большое значение —
      // остаток тогда равен самому отступу, и стрелка стоит где поставлена.
      aSpan[idx] = pl.moving ? spanLocal : 1e9;
      aSpeed[idx] = speedLocal;

      // ── Начальный сдвиг ────────────────────────────────────────────
      //
      // Место стрелки вдоль выработки: её номер в цепочке, помноженный на шаг.
      // Всё в локальных единицах — шейдер прибавляет этот сдвиг к координате X
      // и берёт остаток по длине цикла.
      const along = (pl.step * i) / pl.aLen;

      // Привязка к ОБЩЕМУ НУЛЮ схемы — только для движущихся стрелок.
      //
      // Без неё каждая выработка отсчитывала бы фазу от своего начала, и на
      // стыке стрелки шли бы вразнобой: в одной поток только что прошёл, в
      // другой ещё на подходе. Сдвиг на расстояние от начала координат до
      // начала выработки ставит все цепочки на одну мировую сетку — соседние
      // выработки продолжают друг друга, и поток читается как сквозной.
      //
      // Неподвижным стрелкам привязка не нужна и вредна: она сдвинула бы их
      // с выбранных мест, а стоящая стрелка обязана быть там, где поставлена.
      const worldPhase = pl.moving ? -(pl.from.dot(pl.dir) + pl.margin) / pl.aLen : 0;

      // Приводим по модулю ЗДЕСЬ, а не в шейдере. Координаты рудника — это
      // тысячи метров, делённые на длину стрелки: число выходит большим, и
      // мировой сдвиг у соседних выработок отличался бы уже за пределами
      // точности float — стрелки поехали бы вразнобой именно там, где должны
      // сойтись. После приведения остаётся дробная часть цикла, и точности
      // хватает с запасом.
      const raw = along + worldPhase;
      aPhase[idx] = pl.moving
        ? ((raw % spanLocal) + spanLocal) % spanLocal
        : along;   // стоящая стрелка — просто своё место, без приведения
      idx++;
    }
  }

  geom.setAttribute("aSpan", new THREE.InstancedBufferAttribute(aSpan, 1));
  geom.setAttribute("aSpeed", new THREE.InstancedBufferAttribute(aSpeed, 1));
  geom.setAttribute("aPhase", new THREE.InstancedBufferAttribute(aPhase, 1));

  mesh.instanceMatrix.needsUpdate = true;
  if (mesh.instanceColor) mesh.instanceColor.needsUpdate = true;

  return {
    mesh,
    arrowCount: total,
    setTime(seconds: number) { timeUniform.value = seconds; },
    dispose() {
      geom.dispose();
      mat.dispose();
    },
  };
}