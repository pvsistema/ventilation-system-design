import { mergeGeometries } from "three/examples/jsm/utils/BufferGeometryUtils.js";
import { type TopoNode, type TopoBranch } from "@/lib/topology";
import { sectionOutline } from "@/lib/tube3d";
import { toThree } from "./mineScene";
import { arrowSpeedMps } from "@/lib/flowAnim";

/**
 * Ниже этого расхода стрелку не ставим.
 *
 * Тот же порог, что на чертеже: около нуля знак расхода — это уже не
 * направление, а погрешность расчёта, и показывать по нему стрелку нельзя.
 */
const MIN_FLOW = 0.1;

/** Цвета струи — те же, что на чертеже. */
const COLOR_FRESH = 0xdc2626;     // свежая
const COLOR_POLLUTED = 0x2563eb;  // загазованная (исходящая)

/** Граней в конусе. Двенадцати хватает: стрелка мелкая, ребра на ней не видны. */
const CONE_FACETS = 12;

/**
 * Сколько стрелок максимум на одной выработке.
 *
 * Было 5. При общем шаге потока этого мало: на стволе в сорок шагов пять
 * стрелок покрывали лишь середину, а концы оставались пустыми — поток
 * выглядел оборванным. Теперь цепочка тянется по всей длине; общее число
 * стрелок всё равно ограничено MAX_TOTAL.
 */
const MAX_PER_BRANCH = 14;

/**
 * ЕДИНЫЙ ШАГ ПОТОКА, доля от длины стрелки.
 *
 * ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО. Стрелка «бежит» от начала своей выработки до конца и
 * возвращается в начало — иначе её пришлось бы вести через узел в следующую
 * выработку, а там развилка: воздух делится на два-три потока, и одна стрелка
 * физически не может продолжиться во все сразу.
 *
 * Значит, у каждой выработки свой цикл. И вот если длина цикла у каждой своя,
 * поток рассыпается: на длинном штреке стрелка идёт полторы секунды, на
 * короткой сбойке — пятую долю, и там она «дёргается», мелькая туда-сюда
 * заметно чаще соседей. Ровно это и видно на снимке.
 *
 * Лечится тем, что шаг между стрелками делается ОДИНАКОВЫМ по всей схеме (в
 * метрах рудника), а длина цикла берётся равной этому шагу. Тогда стрелка
 * пробегает ровно до места, где её сменит следующая, — и цикл выходит одним и
 * тем же на любой выработке. Плюс фаза отсчитывается от общего нуля по
 * пройденному расстоянию, так что и в соседних выработках стрелки идут в лад,
 * будто это один сквозной поток.
 *
 * ПОЧЕМУ 3,4, А НЕ МЕНЬШЕ. Число — это шаг в длинах самой стрелки, значит
 * просвет между ними равен K − 1. При 2,2 просвет выходил чуть больше длины
 * стрелки: цепочка читалась как сплошная колбаса, отдельных указателей в ней
 * было не различить. При 3,4 между стрелками остаётся два с лишним корпуса —
 * поток виден как поток, а стрелка как стрелка.
 */
const FLOW_PITCH_K = 3.4;

/**
 * Потолок общего числа стрелок.
 *
 * Отрисовка у них одна на всех, но каждая занимает место в памяти видеокарты.
 * На схеме, где стрелок больше этого числа, они всё равно сливаются, поэтому
 * лишние просто не ставим.
 */
const MAX_TOTAL = 20000;

export interface ArrowsInput {
  nodes: TopoNode[];
  branches: TopoBranch[];
  xyScale: number;
  zScale: number;
  /**
   * Выработки с загазованной (исходящей) струёй — красятся синим.
   * Считается снаружи, тем же расчётом, что и на чертеже.
   */
  pollutedBranchIds?: Set<string>;
  /** Множитель скорости анимации из настроек: 1 — обычная, 0.5 — вдвое медленнее. */
  animSpeed?: number;
  /**
   * Вести стрелку ВНУТРИ выработки, по её оси.
   *
   * Так читается лучше всего: видно не просто направление, а именно то, что
   * воздух идёт ПО этой выработке. Смысл появляется только на прозрачном теле —
   * в сплошном режиме стрелка внутри трубы не видна вовсе, и тогда её выносят
   * наружу (см. offsetNormal). Поэтому решение принимает вызывающая сторона,
   * которая знает текущую плотность показа.
   */
  inside?: boolean;
}

