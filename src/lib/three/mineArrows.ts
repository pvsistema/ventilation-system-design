/**
 * Ниже этого расхода стрелку не ставим.
 *
 * Тот же порог, что на чертеже: около нуля знак расхода — это уже не
 * направление, а погрешность расчёта, и показывать по нему стрелку нельзя.
 */
const MIN_FLOW = 0.1;

/** Цвета струи — те же, что на чертеже. */
const COLOR_FRESH = 0xdc2626;     // свежая
const COLOR_POLLUTED = 0x2563eb;  // загазованная (исходящая)

/** Граней в конусе. Двенадцати хватает: стрелка мелкая, ребра на ней не видны. */
const CONE_FACETS = 12;

/**
 * Минимальная длительность пробега стрелки по выработке, секунд.
 *
 * ЕДИНСТВЕННАЯ поправка к честной скорости, и только в одну сторону — вниз.
 *
 * На короткой сбойке при сильной струе стрелка пролетает свой путь за сотые
 * доли секунды и возвращается в начало: глаз видит не движение, а мерцание, и
 * направление по такой стрелке не прочитать вовсе. Нижний предел держит ход
 * различимым.
 *
 * ВЕРХНЕГО предела длительности здесь СОЗНАТЕЛЬНО НЕТ (раньше стоял потолок в
 * 6 секунд, и он-то и врал о скорости). Рассуждение «на длинном стволе пробег
 * занимает минуту, значит стрелка кажется стоящей» неверно: глаз оценивает
 * движение по скорости на экране, а не по тому, когда стрелка добежит до
 * конца. Зато потолок делал вот что: скорость превращалась в ДЛИНУ пробега,
 * делённую на 6 секунд, то есть зависела от длины выработки и переставала
 * зависеть от скорости воздуха. Километровый ствол с вялой струёй гнал стрелку
 * в разы быстрее, чем короткий штрек с сильной, — показ прямо противоречил
 * расчёту. На чертеже такого ограничения никогда не было (там предел стоит на
 * СКОРОСТИ — FLOW_PX_MIN/FLOW_PX_MAX), поэтому два режима ещё и расходились.
 */
const MIN_CYCLE_SEC = 0.6;

/**
 * Потолок общего числа стрелок.
 *
 * Отрисовка у них одна на всех, но каждая занимает место в памяти видеокарты.
 * На схеме, где стрелок больше этого числа, они всё равно сливаются, поэтому
 * лишние просто не ставим.
 */
const MAX_TOTAL = 20000;

export interface ArrowsInput {
  nodes: TopoNode[];
  branches: TopoBranch[];
  xyScale: number;
  zScale: number;
  /**
   * Выработки с загазованной (исходящей) струёй — красятся синим.
   * Считается снаружи, тем же расчётом, что и на чертеже.
   */
  pollutedBranchIds?: Set<string>;
  /** Множитель скорости анимации из настроек: 1 — обычная, 0.5 — вдвое медленнее. */
  animSpeed?: number;
  /**
   * Вести стрелку ВНУТРИ выработки, по её оси.
   *
   * Так читается лучше всего: видно не просто направление, а именно то, что
   * воздух идёт ПО этой выработке. Смысл появляется только на прозрачном теле —
   * в сплошном режиме стрелка внутри трубы не видна вовсе, и тогда её выносят
   * наружу (см. offsetNormal). Поэтому решение принимает вызывающая сторона,
   * которая знает текущую плотность показа.
   */
  inside?: boolean;
}

/** Готовые стрелки: меш для сцены плюс управление временем и уборка. */
