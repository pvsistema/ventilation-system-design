// ─────────────────────────────────────────────────────────────────────────────
// branchWidthBySection.ts — толщина ветви по площади её сечения.
//
// ЗАЧЕМ. По умолчанию все выработки на схеме одной толщины: ствол 30 м² и
// вентсбойка 2 м² выглядят одинаково. Из-за этого:
//   • не видно фактической модели — схема не похожа на план горных работ;
//   • ошибка ввода сечения (2.0 вместо 20) ничем себя не выдаёт и всплывает
//     только на расчёте, когда доверять результату уже нельзя.
//
// Здесь толщина линии привязывается к сечению. Расчёт вынесен в общий модуль,
// потому что подписи и линии рисуются в ТРЁХ местах (SVG-холст, Canvas-рендерер
// и экспорт SVG) — иначе режимы разошлись бы между экраном и печатью.
//
// ПОЧЕМУ КОРЕНЬ, А НЕ ПРЯМАЯ ПРОПОРЦИЯ. На руднике сечения различаются в
// десятки раз (1…40 м²). При прямой пропорции узкие выработки вырождаются в
// нитку, а стволы сливаются в пятно — работать со схемой невозможно. Квадратный
// корень сжимает диапазон: ширина линии становится пропорциональна ЛИНЕЙНОМУ
// размеру выработки, что заодно физически честнее «толщины на плане».
//
// ЗА ЭТАЛОН берём медиану сечений, а не среднее: одна ошибочная ветвь в 500 м²
// не должна перекашивать всю схему — именно такие ошибки мы и ищем.
// ─────────────────────────────────────────────────────────────────────────────
import { type TopoBranch } from "./topology";

/** Эталонное сечение схемы (медиана) — относительно него считается толщина. */
export function medianSection(branches: TopoBranch[]): number {
  const areas: number[] = [];
  for (const b of branches) {
    const a = b.area ?? 0;
    // Нулевые и явно ошибочные сечения в эталон не берём: они не должны
    // задавать масштаб для всей схемы.
    if (a > 0.01) areas.push(a);
  }
  if (areas.length === 0) return 0;
  areas.sort((x, y) => x - y);
  const mid = areas.length >> 1;
  return areas.length % 2 ? areas[mid] : (areas[mid - 1] + areas[mid]) / 2;
}

/**
 * Толщина ветви с учётом её сечения.
 *
 * base      — обычная толщина (настройка схемы или ручная у ветви);
 * area      — сечение этой выработки, м²;
 * median    — эталонное сечение схемы (см. medianSection);
 * minPct/maxPct — пределы из настроек «Пределы масштабов», % от базовой.
 *
 * Возвращает базовую толщину, если считать не от чего: сечение не задано или
 * схема пустая. Так ветвь с нулевым сечением не исчезнет со схемы — её видно,
 * и она подсвечивается отдельно (см. hasBadSection).
 */
export function widthBySection(
  base: number,
  area: number,
  median: number,
  minPct = 30,
  maxPct = 300,
): number {
  if (!(median > 0) || !(area > 0.01)) return base;
  const k = Math.sqrt(area / median);
  const lo = Math.max(0.05, minPct / 100);
  const hi = Math.max(lo, maxPct / 100);
  return base * Math.min(hi, Math.max(lo, k));
}

/**
 * Сечение выглядит ошибочным: не задано или за пределами разумного для горной
 * выработки. Такие ветви подсвечиваются, чтобы ошибку было видно на схеме, а не
 * на расчёте.
 *
 * Верхний предел намеренно щедрый (200 м²): бывают камеры большого сечения, и
 * ложная тревога здесь хуже пропуска.
 */
export function hasBadSection(b: TopoBranch): boolean {
  const a = b.area ?? 0;
  if (b.isVentPipeBranch) return false;   // линия вентстава — не выработка
  return !(a > 0.05) || a > 200;
}
