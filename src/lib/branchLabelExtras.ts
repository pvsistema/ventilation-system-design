// ─────────────────────────────────────────────────────────────────────────────
// branchLabelExtras.ts — значения для четырёх индикаторов ветви, которые есть
// в «Панели информации», но не хранятся в TopoBranch готовым числом:
//
//   • Суммарное сопротивление (Rсум)   — выработка + перемычка + окно ГВУ
//   • Дополнительная депрессия (ДопН)  — напор вентилятора на ветви
//   • Высота ветви (Высота)            — высота сечения по его форме
//   • Количество людей (Людей)         — численность в забое
//
// Раньше галочки в панели были, а на схеме ничего не появлялось: подписи
// строились в трёх местах (SVG-холст, Canvas-рендерер, экспорт SVG) и ни в
// одном из них этих четырёх величин не было. Формулы вынесены сюда, чтобы все
// три режима показывали ОДНО И ТО ЖЕ число и совпадали с панелью свойств.
// ─────────────────────────────────────────────────────────────────────────────
import { type TopoBranch } from "./topology";
import { branchBulkheadRkMurg } from "./bulkheads";

/**
 * Суммарное (общее) сопротивление ветви, кМюрг (Н·с²/м⁸).
 * Та же сумма, что в строке «Общее сопр. R» свойств ветви:
 * сопротивление выработки + перемычки/окна + окна ГВУ (вентилятор,
 * установленный «Внутри перемычки»).
 */
export function branchTotalR(b: TopoBranch): number {
  const fanCrossingKmu = (b.hasFan && (b.fanInstall ?? "Внутри перемычки") === "Внутри перемычки")
    ? (b.fanCrossingR ?? 0) / 1000 : 0;
  return (b.resistance ?? 0) + branchBulkheadRkMurg(b) + fanCrossingKmu;
}

/**
 * Дополнительная депрессия ветви, Па — напор источника (вентилятора),
 * установленного на ветви. Без вентилятора — 0 (строка «Доп. депрессия»
 * в свойствах ветви показывает ровно это).
 */
export function branchExtraPressure(b: TopoBranch): number {
  return b.hasFan ? (b.fanPressure ?? 0) : 0;
}

/**
 * Высота сечения выработки, м — считается по форме сечения:
 *   круглое        → диаметр;
 *   прямоугольное  → высота прямоугольника;
 *   трапеция       → высота трапеции;
 *   арочное        → высота прямых стен + стрела свода;
 *   произвольное   → неизвестна (0), в подпись не попадёт.
 */
export function branchSectionHeight(b: TopoBranch): number {
  switch (b.shape) {
    case "round": return b.diameter ?? 0;
    case "rect":  return b.rectHeight ?? 0;
    case "trap":  return b.rectHeight ?? 0;
    case "arch": {
      const a = b.rectWidth ?? 0;
      const wall = b.rectHeight ?? 0;
      // Стрела свода не больше полукруга; по умолчанию — полукруг (a/2).
      const arch = (b.archHeight ?? 0) > 0 ? Math.min(b.archHeight, a / 2) : a / 2;
      return wall + arch;
    }
    default: return 0;
  }
}

/** Количество людей в забое на ветви, чел (вкладка «Вентиляция» → забой). */
export function branchPeopleCount(b: TopoBranch): number {
  return Math.max(0, Math.round(b.ventPeopleCount ?? 0));
}
