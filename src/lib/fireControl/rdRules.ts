// ─────────────────────────────────────────────────────────────────────────────
// rdRules.ts — проверка подобранного режима на соответствие РД-15-11-2007, п.30.
//
// ЗАЧЕМ. Подбор оптимизирует числа: людей в риске, превышения скорости. Но
// нормативный документ содержит ПРЕДПИСАНИЯ, которые числами не выражаются:
// при пожаре в стволе реверс нужен независимо от того, лучше ли стало на
// единицу в статистике, а при взрыве газа направление струи на главных
// выработках, наоборот, положено сохранять.
//
// Такой режим нельзя утвердить в плане ликвидации аварий, даже если по людям
// он выигрывает. Поэтому проверка выдаёт ПРЕДУПРЕЖДЕНИЯ, а не молча меняет
// порядок вариантов: решение остаётся за инженером, но основание для решения
// он видит.
//
// Расчётов здесь нет — только сопоставление свойств схемы с текстом п.30.
// ─────────────────────────────────────────────────────────────────────────────
import type { TopoBranch, TopoNode } from "@/lib/topology";
import type { FireAction } from "./actions";

/** Одно замечание по соответствию РД. */
export interface RdNote {
  /**
   * «required» — РД предписывает то, чего в варианте НЕТ (режим спорный);
   * «violation» — вариант делает то, что РД в этом случае не рекомендует;
   * «info» — пояснение к обстановке, без оценки варианта.
   */
  kind: "required" | "violation" | "info";
  /** Пункт документа — чтобы замечание можно было проверить по первоисточнику. */
  clause: string;
  text: string;
}

/**
 * Типы выработок, для которых п.30 предписывает РЕВЕРС при пожаре.
 *
 * Дословно: «пожары в надшахтных зданиях, в стволах шахт, в околоствольных
 * дворах, в главных квершлагах (штреках) и в примыкающих к ним камерах, не
 * имеющих обособленного проветривания, ПО КОТОРЫМ ПОСТУПАЕТ СВЕЖИЙ ВОЗДУХ».
 *
 * Последнее условие ключевое: реверс нужен, когда очаг стоит на СВЕЖЕЙ струе
 * и дым идёт в шахту к людям. Пожар в исходящей струе реверсом не лечится.
 */
const REVERSE_TYPE_PATTERNS = [
  /ствол/i, /надшахтн/i, /околоствольн/i, /квершлаг/i, /штольн/i, /копёр|копер/i,
];

/** Тип выработки требует реверса по п.30? */
function isReverseProneType(b: TopoBranch): boolean {
  const t = `${b.type ?? ""} ${b.mineTypeName ?? ""}`;
  return REVERSE_TYPE_PATTERNS.some(re => re.test(t));
}

/** Вертикальная или наклонная выработка между горизонтами. */
function isInclinedOrVertical(b: TopoBranch): boolean {
  return Math.abs(b.angle ?? 0) >= 10;
}

export interface RdCheckInput {
  branches: TopoBranch[];
  nodes: TopoNode[];
  /** Действия проверяемого варианта. Пустой список — исходный режим. */
  actions: FireAction[];
  /** Ветви, где струя опрокинулась относительно штатного режима. */
  reversedBranchCount: number;
}

/**
 * Проверить вариант по правилам п.30.
 *
 * Возвращает список замечаний. Пустой список означает, что явных расхождений
 * с документом нет — но НЕ означает, что режим автоматически годен: п.30
 * описывает лишь типовые случаи.
 */
export function checkRdRules(input: RdCheckInput): RdNote[] {
  const { branches, actions, reversedBranchCount } = input;
  const notes: RdNote[] = [];

  const fireBranches = branches.filter(b => b.hasFire);
  if (fireBranches.length === 0) return notes;

  const hasReverseAction = actions.some(a => a.kind === "fan_reverse");
  const hasStopAction = actions.some(a => a.kind === "fan_stop");

  // ── Пожар в стволе / надшахтном здании / околоствольном дворе ────────────
  // Реверс предписан, когда очаг на выработке со СВЕЖЕЙ струёй: дым идёт
  // вглубь шахты, навстречу людям.
  const reverseProne = fireBranches.filter(isReverseProneType);
  if (reverseProne.length > 0) {
    const names = reverseProne
      .map(b => b.type?.trim() || b.mineTypeName?.trim() || `выработка ${b.id.slice(-4)}`)
      .join(", ");
    if (!hasReverseAction && reversedBranchCount === 0) {
      notes.push({
        kind: "required",
        clause: "п.30",
        text: `Очаг в выработке, по которой поступает свежий воздух (${names}). `
          + "РД предписывает реверсирование вентиляционной струи — в варианте его нет.",
      });
    } else {
      notes.push({
        kind: "info",
        clause: "п.30",
        text: `Очаг в выработке со свежей струёй (${names}) — реверсирование соответствует РД.`,
      });
    }
  }

  // ── Пожар в вертикальной/наклонной выработке между горизонтами ───────────
  // Режим берётся тот же, что при пожаре в сопряжении с ВЕРХНИМ горизонтом.
  // Проверить это автоматически нельзя (нужна позиция ПЛА верхнего горизонта),
  // поэтому выдаём напоминание — молчать о требовании документа нельзя.
  const inclined = fireBranches.filter(isInclinedOrVertical);
  if (inclined.length > 0) {
    notes.push({
      kind: "info",
      clause: "п.30",
      text: "Очаг в наклонной (вертикальной) выработке, соединяющей горизонты: "
        + "режим должен совпадать с предусмотренным при пожаре в сопряжении с ВЕРХНИМ горизонтом. "
        + "Сверьте с соответствующей позицией плана.",
    });
  }

  // ── Остановка главной вентиляционной установки ──────────────────────────
  // При пожаре в здании ГВУ и одном вентиляторе п.30 требует остановить его
  // и перекрыть доступ продуктов горения лядами. При нескольких ВГП — выбрать
  // режим, исключающий попадание дыма в шахту при остановке аварийного.
  const mainFans = branches.filter(b => b.hasFan && (b.fanType === "ГВУ" || b.fanType === "ВВУ"));
  const stoppedMain = actions.filter(a =>
    a.kind === "fan_stop" && mainFans.some(b => b.id === a.branchId));
  if (stoppedMain.length > 0) {
    notes.push({
      kind: "info",
      clause: "п.30",
      text: mainFans.length > 1
        ? "Останавливается главная вентиляционная установка при нескольких ВГП — убедитесь, "
          + "что режим исключает проникновение продуктов горения в шахту через остановленный вентилятор."
        : "Останавливается единственная главная вентиляционная установка — по РД одновременно "
          + "перекрывают доступ продуктов горения в шахту лядами.",
    });
  }

  // ── Самостоятельное опрокидывание струи тепловой депрессией (п.29) ───────
  // Отдельное требование: учитывать возможность опрокидывания при определении
  // путей вывода людей. Если решатель показал опрокинутые ветви — это факт,
  // а не гипотеза, и умолчать о нём нельзя.
  if (reversedBranchCount > 0 && !hasReverseAction && !hasStopAction) {
    notes.push({
      kind: "info",
      clause: "п.29",
      text: `Тепловая депрессия пожара опрокидывает струю в ${reversedBranchCount} выработках `
        + "без вмешательства. Пути вывода людей определять с учётом этого опрокидывания.",
    });
  }

  return notes;
}

/** Есть ли среди замечаний расхождение с предписанием РД. */
export function hasRdProblem(notes: RdNote[]): boolean {
  return notes.some(n => n.kind === "required" || n.kind === "violation");
}
