-- Снятие ПРОВЕРОЧНОЙ привязки с ключа #3 «Якутское Золото».
--
-- Автопривязка проверена на живом сервере и работает верно: ключ закрепился за
-- первым компьютером, второй получил отказ wrong_computer, первый продолжил
-- работать. Но закрепился он за ПРОВЕРОЧНЫМ отпечатком, а не за настоящим
-- рудником. Эту привязку нужно снять, иначе настоящий компьютер заказчика по
-- ключу не заработает.
--
-- Записи проверочных мест удалить нельзя (защита от потери данных), поэтому
-- помечаем их как отключённые: расчётные серверы и лицензионный сервис
-- заблокированные места в расчёт не берут (см. _load_offline_keys и ветку
-- is_blocked в offline_check), а счётчик занятых мест пересчитывается по
-- незаблокированным.
--
-- Автопривязку оставляем включённой: ключ закрепится сам, когда на руднике
-- впервые появится интернет. Ровно ради этого случая всё и делалось.
UPDATE offline_key_seats
SET is_blocked = TRUE,
    hostname = COALESCE(hostname, '') || ' (проверка автопривязки, отключено)'
WHERE offline_key_id = 3 AND hostname LIKE 'ПРОВЕРКА-%';

UPDATE offline_keys
SET bound_fp = NULL
WHERE id = 3;

INSERT INTO license_events (event_type, detail)
VALUES ('offline_binding_reset',
        'Ключ #3: снята проверочная привязка; автопривязка ждёт первой связи с рудника');
