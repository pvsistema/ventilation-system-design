-- Снятие проверочной привязки, оставшейся после проверки отображения.
--
-- Проверка подтвердила: в панели видно код компьютера, его имя и дату
-- срабатывания автопривязки. Теперь возвращаем ключ #3 в чистое состояние —
-- он должен закрепиться за НАСТОЯЩИМ компьютером рудника при первой связи.
--
-- Записи удалять нельзя (защита от потери данных), поэтому помечаем
-- проверочные места отключёнными: они не занимают лимит и не попадают ни в
-- счётчик, ни в сведения о привязке (см. list_offline_keys — везде добавлено
-- условие is_blocked = FALSE).
UPDATE offline_key_seats
SET is_blocked = TRUE
WHERE offline_key_id = 3
  AND (hostname LIKE 'ПРОВЕРКА-%' OR hostname IS NULL);

UPDATE offline_keys
SET bound_fp = NULL, autobind = TRUE
WHERE id = 3;

INSERT INTO license_events (event_type, detail)
VALUES ('offline_binding_reset',
        'Ключ #3: снята привязка после проверки отображения; ждёт связи с рудника');
