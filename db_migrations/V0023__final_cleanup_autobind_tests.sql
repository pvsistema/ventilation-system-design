-- Окончательная очистка проверочных привязок ключа #3 «Якутское Золото».
--
-- Проверка завершена и подтвердила: автопривязка работает, заблокированные
-- места не занимают лимит, и после их отключения ключ снова готов закрепиться
-- за новым компьютером.
--
-- Теперь снимаем ВСЕ проверочные следы, чтобы ключ ушёл к заказчику чистым:
-- настоящий компьютер рудника должен закрепиться сам при первом интернете.
UPDATE offline_key_seats
SET is_blocked = TRUE
WHERE offline_key_id = 3 AND hostname LIKE 'ПРОВЕРКА-%';

UPDATE offline_keys
SET bound_fp = NULL, autobind = TRUE
WHERE id = 3;

INSERT INTO license_events (event_type, detail)
VALUES ('offline_binding_reset',
        'Ключ #3: все проверочные привязки сняты; ждёт первой связи с рудника');
