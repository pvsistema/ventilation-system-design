-- ─────────────────────────────────────────────────────────────────────────────
-- Устранение слабых мест лицензирования.
--
-- 1. РЕЖИМ ПРОВЕРКИ РАСЧЁТОВ ПЕРЕЕЗЖАЕТ В БАЗУ.
--    Раньше строгий режим включался только переменной окружения в каждой из
--    пяти расчётных функций: чтобы перевести систему, требовалось пять раз
--    зайти в настройки и передеплоить. Откатить при беде — так же долго.
--    Теперь режим хранится здесь, а расчётные серверы читают его с коротким
--    кэшем. Переключение и откат — одна кнопка в админ-панели.
--
-- 2. ДЕМО-КВОТА НА СЕРВЕРЕ.
--    Демо держалось только на интерфейсе (лимит узлов в Cad.tsx), а расчётный
--    сервер считал любую схему. Правка одной строки в файлах программы
--    открывала полный расчёт. Теперь предел размера задачи задаётся здесь и
--    проверяется сервером.
--
-- 3. УЧЁТ ПЕРЕВЫПУСКА АВАРИЙНЫХ КЛЮЧЕЙ.
--    Выданные PVSO-ключи не имели привязки к компьютеру и свободно
--    копировались. Для перевыпуска с привязкой нужны поля: кем заменён ключ
--    и когда он отозван — чтобы в панели было видно, какой ключ кого сменил.
-- ─────────────────────────────────────────────────────────────────────────────

INSERT INTO app_settings (key, value) VALUES
    -- soft — считаем всем, ведём учёт; strict — без лицензии отказ.
    ('compute_license_mode', 'soft'),
    -- Предел размера задачи для расчёта БЕЗ лицензии в строгом режиме.
    -- Совпадает с лимитом демо-режима в интерфейсе (20 узлов).
    ('compute_demo_max_nodes', '20'),
    -- Ветвей в демо-схеме: узлов обычно меньше, чем выработок, поэтому
    -- отдельный предел — иначе 20 узлов можно связать сотней ветвей.
    ('compute_demo_max_branches', '30')
ON CONFLICT (key) DO NOTHING;

-- Какой ключ пришёл на смену отозванному (для перевыпуска с привязкой к ПК).
ALTER TABLE offline_keys
    ADD COLUMN IF NOT EXISTS replaced_by_id INTEGER,
    ADD COLUMN IF NOT EXISTS revoked_at     TIMESTAMPTZ;

COMMENT ON COLUMN offline_keys.replaced_by_id IS
    'Номер ключа, выпущенного взамен этого при перевыпуске с привязкой к ПК';
COMMENT ON COLUMN offline_keys.revoked_at IS
    'Когда ключ отозван (is_active = FALSE)';

-- Быстрая выборка отозванных ключей: расчётный сервер подтягивает этот
-- список, чтобы отозванный PVSO не проходил даже при подстановке в запрос
-- напрямую, минуя программу.
CREATE INDEX IF NOT EXISTS idx_offline_keys_active
    ON offline_keys (id) WHERE is_active = FALSE;
