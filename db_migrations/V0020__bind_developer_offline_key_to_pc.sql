-- Привязка аварийного ключа «Разработчик» (#4) к конкретному компьютеру.
--
-- ПОЧЕМУ БЕЗ ПЕРЕВЫПУСКА. Расчётные серверы теперь берут привязку ИЗ РЕЕСТРА
-- (см. backend/*/license_guard.py, _load_offline_keys), а не только из подписи
-- внутри ключа. Поэтому достаточно проставить привязку здесь: ключ немедленно
-- становится непереносимым, а работа на своём компьютере не прерывается и
-- новый ключ никому передавать не нужно.
--
-- Перевыпуск понадобился бы, только если бы привязку читала исключительно
-- подпись — тогда старый ключ пришлось бы отзывать и рассылать новый, остановив
-- людям работу до получения. Здесь этого не требуется.
--
-- ЧТО ЗАПИСЫВАЕМ. Хэш отпечатка того ПК, который уже выходил на связь по ключу
-- (ПВ-Система, Ipatov, Windows). Именно хэш, а не код рабочего места: в реестре
-- мест хранится sha256 отпечатка, и восстановить из него короткий код нельзя —
-- функция односторонняя. Расчётный сервер сверяет привязку длиной ≥32 знаков с
-- хэшем, который присылает программа.
--
-- Число мест снижаем с 12 до 1: ключ теперь работает на одном компьютере,
-- прежний запас потерял смысл.
UPDATE offline_keys o
SET bound_fp = (
        SELECT s.fingerprint FROM offline_key_seats s
        WHERE s.offline_key_id = o.id
        ORDER BY s.last_seen_at DESC LIMIT 1
    ),
    seats = 1
WHERE o.id = 4
  AND o.bound_fp IS NULL
  AND EXISTS (SELECT 1 FROM offline_key_seats s WHERE s.offline_key_id = o.id);

INSERT INTO license_events (event_type, detail)
VALUES ('offline_key_bound',
        'Ключ #4 «Разработчик» привязан к ПК из реестра; мест 12 -> 1');
