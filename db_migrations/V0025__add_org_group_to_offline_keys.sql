-- Головная организация аварийного ключа.
--
-- Аварийные ключи выдаются филиалам крупных структур (ФГУП «ВГСЧ» и т.п.)
-- ровно так же, как обычные лицензии. Без группировки реестр на два десятка
-- филиалов превращается в сплошной список, где отдельные организации теряются.
--
-- Поле необязательное: ключи без группы остаются отдельными строками
-- верхнего уровня, как было раньше.
ALTER TABLE offline_keys ADD COLUMN IF NOT EXISTS org_group TEXT;

-- Выборка реестра всегда идёт с сортировкой и группировкой по этому полю.
CREATE INDEX IF NOT EXISTS idx_offline_keys_org_group ON offline_keys (org_group);