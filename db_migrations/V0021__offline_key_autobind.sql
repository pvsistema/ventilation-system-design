-- ─────────────────────────────────────────────────────────────────────────────
-- АВТОПРИВЯЗКА АВАРИЙНОГО КЛЮЧА К РАБОЧЕМУ МЕСТУ.
--
-- ЗАЧЕМ. Привязка к компьютеру делает ключ непереносимым, но требует кода
-- рабочего места — человек должен продиктовать его из окна «Лицензия». На
-- отдалённом руднике это часто невозможно: связи нет, спросить некого, а ключ
-- нужен сейчас. Из-за этого ключи выдавались вообще без привязки и свободно
-- копировались на любое число машин.
--
-- Теперь ключ может закрепиться САМ: при первом выходе на связь сервер
-- записывает отпечаток компьютера, который отметился, и дальше ключ работает
-- только на нём. Код спрашивать не нужно — достаточно, чтобы на месте один раз
-- появился интернет.
--
-- Сколько именно компьютеров закрепится — задаёт число мест (seats) у ключа.
-- Ключ на 3 места закрепится за первыми тремя ПК, четвёртый получит отказ.
--
-- autobind = TRUE по умолчанию для НОВЫХ ключей: безопасное поведение должно
-- быть поведением по умолчанию. Уже выданные ключи не трогаем — у них своя
-- история, менять правила на ходу нельзя.
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE offline_keys
    ADD COLUMN IF NOT EXISTS autobind BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN offline_keys.autobind IS
    'Ключ сам закрепляется за компьютерами, которые первыми вышли на связь '
    '(в пределах числа мест). Не требует кода рабочего места от человека';

-- Когда автопривязка сработала — видно в панели и в журнале.
ALTER TABLE offline_key_seats
    ADD COLUMN IF NOT EXISTS bound_at TIMESTAMPTZ;

COMMENT ON COLUMN offline_key_seats.bound_at IS
    'Момент, когда ключ автоматически закрепился за этим компьютером';

-- Уже выданные ключи: автопривязку НЕ включаем задним числом.
--
-- Ключ #4 «Разработчик» уже привязан вручную к своему ПК — там она не нужна.
-- Ключ #3 «Якутское Золото» ни разу не выходил на связь: включаем автопривязку
-- именно ему. Это ровно тот случай, ради которого всё и делается — удалённый
-- рудник, код ПК получить неоткуда. Ключ закрепится сам при первом интернете.
UPDATE offline_keys SET autobind = FALSE WHERE bound_fp IS NOT NULL;
UPDATE offline_keys SET autobind = TRUE  WHERE id = 3 AND bound_fp IS NULL;

INSERT INTO license_events (event_type, detail)
VALUES ('offline_autobind_enabled',
        'Включена автопривязка: ключ #3 закрепится за первым ПК, вышедшим на связь');
