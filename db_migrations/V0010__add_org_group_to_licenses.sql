-- Группа (головная организация) для лицензий.
-- Нужна, чтобы в админ-панели филиалы одной структуры — например ФГУП «ВГСЧ» —
-- сворачивались в один раскрывающийся раздел, а не шли сплошным списком.
-- NULL = лицензия вне групп, показывается отдельной строкой верхнего уровня.
ALTER TABLE licenses ADD COLUMN IF NOT EXISTS org_group VARCHAR(200);

-- Индекс: список лицензий всегда группируется по этому полю.
CREATE INDEX IF NOT EXISTS idx_licenses_org_group ON licenses (org_group);

-- Первичное заполнение: все филиалы ВГСЧ и сама головная организация
-- объединяются в группу «ФГУП "ВГСЧ"». Это ровно те записи, что уже есть
-- в базе, — вручную их переназначать не придётся.
UPDATE licenses
SET org_group = 'ФГУП "ВГСЧ"'
WHERE org_group IS NULL
  AND (owner_name LIKE 'Филиал%горноспасательный отряд%'
       OR owner_name LIKE '%ВГСО%'
       OR owner_name = 'ФГУП "ВГСЧ"');